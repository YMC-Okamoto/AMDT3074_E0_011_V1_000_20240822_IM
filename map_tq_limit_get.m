function [tq_min, tq_max] = map_tq_limit_get(speed_rpm, vdc)
% map_tq_limit_get
% 回転速度に応じたトルク上下限（回生側/力行側）をマップから取得する関数
%
% 【この関数の目的】
% モータ・インバータの安全動作範囲を守るため、現在の回転速度に対して
% 許容トルク範囲（最小トルク tq_min、最大トルク tq_max）を返します。
%
% 一般的に高速域になるほど、電圧・電流・熱制約などで
% 出せるトルクが小さくなるため、このような速度依存のリミットを使います。
%
% 【組み込みコード対応】
%   - PE1/src/mapdata_trq_inv0_limit.c
%   - PE1/src/mapdata_trq_inv0_map_limit.c（生テーブル）
%
% 【軸定義（ヘッダ準拠）】
%   X軸（速度）:
%     N_X_2D   = 11
%     ORIGIN_X = 0.0
%     RESO_X   = 500.0
%     → 0, 500, 1000, ... , 5000 [rpm]
%
%   Z軸（DC電圧）:
%     N_Z_2D   = 1
%     ORIGIN_Z = 48.0
%     RESO_Z   = 35.0
%     → 1層のみ（48V層）なので本実装では補間不要
%
% 【入力】
%   speed_rpm : 回転速度 [rpm]
%   vdc       : DCバス電圧 [V]（現状は1層固定のため補間には未使用）
%
% 【出力】
%   tq_min : 回生側トルク下限（通常は負値）[Nm]
%   tq_max : 力行側トルク上限（通常は正値）[Nm]

    % マップ軸パラメータ
    N_X      = 11;     % 速度軸点数
    ORIGIN_X = 0.0;    % 速度軸原点 [rpm]
    RESO_X   = 500.0;  % 速度軸分解能 [rpm/index]
    SCALLING = 1.0;    % 出力スケーリング（組み込み定義に合わせて1.0）

    % -----------------------------------------------------------------
    % 生マップ（48V層）
    % -----------------------------------------------------------------
    % map_tq_limit[1][2][11] 相当データ
    %   map_regen: 回生側制限（負トルク側）
    %   map_power: 力行側制限（正トルク側）
    %
    % 列インデックス対応:
    %   x=0  -> 0 rpm
    %   x=1  -> 500 rpm
    %   ...
    %   x=10 -> 5000 rpm
    map_regen = [-70, -75, -70, -70, -70, -65, -55, -45, -40, -30, -25];
    map_power = [ 75,  70,  70,  60,  45,  35,  30,  25,  20,  15,  15];

    % -----------------------------------------------------------------
    % 速度をマップ上の連続インデックスへ変換
    % -----------------------------------------------------------------
    % abs(speed_rpm) を使う理由：
    % トルク制限マップは通常、速度の絶対値基準で定義されるためです。
    x_nom = (abs(speed_rpm) - ORIGIN_X) / RESO_X;

    % 範囲外アクセス防止
    x_nom = max(0, min(N_X - 1, x_nom));

    % 下側インデックス（0始まり）と補間重み
    xi = min(floor(x_nom), N_X - 2);  % xi+1参照のため上限を N_X-2 に制限
    kw = x_nom - xi;                  % 0～1 の補間重み

    % MATLAB配列（1始まり）へ変換
    xi1 = xi + 1;
    xi2 = xi1 + 1;

    % -----------------------------------------------------------------
    % 線形補間で最終トルク制限を算出
    % -----------------------------------------------------------------
    % tq = (1-kw)*tq(xi1) + kw*tq(xi2)
    tq_min = SCALLING * ((1-kw)*map_regen(xi1) + kw*map_regen(xi2));
    tq_max = SCALLING * ((1-kw)*map_power(xi1) + kw*map_power(xi2));

    % vdcは現状1層マップのため未使用（将来多層化に備えて引数維持）
    %#ok<NASGU>
end