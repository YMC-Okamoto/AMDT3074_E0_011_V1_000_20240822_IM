function s = plant_model_im(s, p, Ts)
% =========================================================================
% plant_model_im.m
%
% 機能:
%   誘導モータ（IM）簡易プラントモデル
%
%   制御シミュレーション専用のモータ応答モデル。
%   コントローラが出力した電圧指令（Vu, Vv, Vw → Vd_ref, Vq_ref）を入力とし、
%   モータの電流応答・磁束・発生トルク・機械速度・機械角を計算する。
%
%   ※ 実機（組み込みソフト）には対応するファイルはない。
%      シミュレーション専用モジュール。
%
%   採用したモデル（誘導モータ 二次磁束方向基準 dq座標系）:
%
%     一次（ステータ）電圧方程式:
%       Vd = R1*id + σ*L1*d(id)/dt - ωe*(σ*L1)*iq
%       Vq = R1*iq + σ*L1*d(iq)/dt + ωe*(σ*L1*id + Lm²/L2 * ψ_r/Lm)
%            ≈ R1*iq + σ*L1*d(iq)/dt + ωe*(σ*L1*id + Lm*id)    [二次磁束 ψ_r = Lm*id 仮定]
%
%     二次磁束方程式（一次遅れ応答）:
%       d(ψ_r)/dt = (Lm/T2)*id - ψ_r/T2
%       ここで T2 = L2/R2 = Lm/R2（二次時定数）
%
%     機械方程式（回転子）:
%       J * d(ωr)/dt = Tmotor - Tload
%       Tmotor = (3/2) * Pp * (Lm/L2) * ψ_r * iq
%              ≈ (3/2) * Pp * ψ_r * iq / 1   [L2 = Lm]
%
%     簡略化の仮定:
%       - L2 = Lm（ロータ漏れインダクタンス無視）
%       - σ*L1 = Ls（ステータ漏れインダクタンス）
%       - 温度補正なし（一定温度での動作を仮定）
%       - 電圧飽和・デッドタイムなし（理想インバータ）
%
% 入力:
%   s   状態構造体（s.Vd_ref, s.Vq_ref, s.wr_mech などを参照）
%   p   パラメータ構造体
%   Ts  積分ステップ幅 [s]（= p.Ts_pwm = 100 µs）
%
% 出力:
%   s   更新後の状態構造体
%       - s.id_plant   [A]    d軸実電流（プラント出力 → コントローラにフィードバック）
%       - s.iq_plant   [A]    q軸実電流
%       - s.iu_ad      [A]    U相電流（Clarke変換入力用）
%       - s.iv_ad      [A]    V相電流
%       - s.iw_ad      [A]    W相電流
%       - s.psi_r      [Wb]   二次磁束（ロータ磁束）
%       - s.torque     [N·m]  発生トルク
%       - s.wr_mech    [rad/s] 機械角速度
%       - s.theta_mech [rad]  機械角（エンコーダ入力用）
%
% データフロー:
%   s.Vd_ref, s.Vq_ref（コントローラ出力）
%   → [IM 電圧方程式積分] → s.id_plant, s.iq_plant, s.psi_r
%   → [トルク演算] → s.torque
%   → [機械方程式積分] → s.wr_mech, s.theta_mech
%   → [逆Park変換] → s.iu_ad, s.iv_ad, s.iw_ad （コントローラへ戻す）
%
% 呼び出し元:
%   im_vector_control_sim.m（PWM割込ごとに呼び出し）
% =========================================================================

% =========================================================================
% プラント側パラメータの取り出し
% =========================================================================
% ステータ漏れインダクタンス（σ*L1 ≈ Ls として近似）
Ls = p.Ls;

% 励磁インダクタンス（L2 = Lm と仮定）
Lm = p.Lm;

% ステータ抵抗
R1 = p.R1;

% ロータ抵抗
R2 = p.R2;

% ロータ時定数 T2 = Lm / R2
T2 = Lm / R2;

% 極対数
Pp = p.Pp;

% 慣性モーメント
J = p.J;

% =========================================================================
% コントローラが使用したdq軸角度を取得
% =========================================================================
% コントローラが計算した theta_dq を使って逆変換を行う
% （閉ループ整合性を保つ）

sin_dq = s.sin_dq;
cos_dq = s.cos_dq;

% =========================================================================
% 実際の電気角速度（コントローラ推定値を使用）
% =========================================================================
% 真の電気角速度 ωe = ωr_mech * Pp + wsl（実際のすべり周波数）
% ここでは近似としてコントローラが推定した winv_ref を使用する。
%
% 理由: ベクトル制御の検証目的上、コントローラのdq軸とプラントのdq軸が
%       一致している状態が正常動作であり、その確認に使う。

wr_e = s.winv_ref;   % 電気角速度（コントローラ推定の一次角周波数）[rad/s]

% =========================================================================
% dq軸電流の微分方程式（オイラー前進法で積分）
% =========================================================================
% 一次電圧方程式より、電流の時間微分を求める:
%
%   d(id)/dt = (Vd - R1*id + ωe*Ls*iq) / Ls
%   d(iq)/dt = (Vq - R1*iq - ωe*Ls*id - ωe*ψ_r) / Ls
%
% ここで ψ_r は二次磁束（ロータ磁束）であり、
% 通常は d軸方向に一致（ベクトル制御の前提）。
%
% ロータ磁束 ψ_r = Lm * id の準定常仮定を適用すると:
%   ωe * ψ_r = ωe * Lm * id
%
% したがって:
%   d(iq)/dt ≈ (Vq - R1*iq - ωe*Ls*id - ωe*Lm*id) / Ls
%             = (Vq - R1*iq - ωe*(Ls+Lm)*id) / Ls

% d(id)/dt の計算（d軸：q軸電流による干渉項を含む）
did_dt = (s.Vd_ref - R1 * s.id_plant + wr_e * Ls * s.iq_plant) / Ls;

% d(iq)/dt の計算（q軸：d軸電流 + 二次磁束による逆起電力項を含む）
diq_dt = (s.Vq_ref - R1 * s.iq_plant - wr_e * Ls * s.id_plant ...
           - wr_e * s.psi_r) / Ls;

% オイラー前進法で電流を更新
s.id_plant = s.id_plant + did_dt * Ts;
s.iq_plant = s.iq_plant + diq_dt * Ts;

% =========================================================================
% 二次磁束（ロータ磁束）の更新
% =========================================================================
% 二次磁束方程式（一次遅れ）:
%   d(ψ_r)/dt = (Lm/T2) * id - ψ_r / T2
%
% 定常状態では: ψ_r = Lm * id（理想ベクトル制御時）

dpsi_dt = (Lm / T2) * s.id_plant - s.psi_r / T2;
s.psi_r = s.psi_r + dpsi_dt * Ts;

% ψ_r が負にならないよう制限（磁束は物理的に負にはならない）
s.psi_r = max(0.0, s.psi_r);

% =========================================================================
% 発生トルクの演算
% =========================================================================
% 誘導モータの発生トルク:
%   Tmotor = (3/2) * Pp * ψ_r * iq
%
% ※ L2 = Lm を仮定したため Lm/L2 = 1

s.torque = (3.0/2.0) * Pp * s.psi_r * s.iq_plant;

% =========================================================================
% 機械方程式の積分（速度・角度更新）
% =========================================================================
% J * d(ωr)/dt = Tmotor - Tload
%
% ここで Tload = p.Tload（定常負荷トルク）

d_wr_dt = (s.torque - p.Tload) / J;
s.wr_mech = s.wr_mech + d_wr_dt * Ts;

% 機械角の積分
s.theta_mech = s.theta_mech + s.wr_mech * Ts;

% theta_mech を 0〜2π に正規化（エンコーダ読み取り模擬用）
s.theta_mech = mod(s.theta_mech, 2*pi);

% =========================================================================
% dq → 3相電流変換（コントローラへのフィードバック用）
% =========================================================================
% dq軸電流 → αβ軸電流（逆Park変換）
ia = cos_dq * s.id_plant - sin_dq * s.iq_plant;
ib = sin_dq * s.id_plant + cos_dq * s.iq_plant;

% αβ軸電流 → 3相電流（逆Clarke変換、振幅不変型）
%   iu =  ia
%   iv = -ia/2 + √3/2 * ib
%   iw = -ia/2 - √3/2 * ib
s.iu_ad =  ia;
s.iv_ad = -ia * 0.5 + ib * (sqrt(3.0)/2.0);
s.iw_ad = -ia * 0.5 - ib * (sqrt(3.0)/2.0);

end
