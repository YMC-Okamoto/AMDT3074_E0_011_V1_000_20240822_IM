function s = fi_pwm_inv0_idqctrl(s, p)
% =========================================================================
% fi_pwm_inv0_idqctrl.m
%
% 機能:
%   PWM割込タスク: dq軸電流PI制御・非干渉補償・電圧指令値演算
%
%   組み込みソフトの fi_pwm_inv0_idqctrl.c に対応するMATLAB版関数。
%   測定したdq軸電流（id_ad, iq_ad）と指令値（id_ref, iq_ref）の偏差に
%   PI制御を施し、さらに非干渉補償電圧を加えて最終的な電圧指令値
%   （Vd_ref, Vq_ref）を生成する。
%
%   処理内容:
%     1) αβ→dq座標変換（Clarke変換 + Park変換）
%     2) d軸電流PIフィードバック制御
%     3) q軸電流PIフィードバック制御
%     4) 非干渉補償（逆起電力・速度起電力のフィードフォワード）
%     5) 電圧ベクトル制限
%     6) 弱め磁束制御（電圧制限超過時にd軸電流指令を補正）
%
% 入力:
%   s   状態構造体（s.id_ad, s.iq_ad, s.id_ref, s.iq_ref などを参照）
%   p   パラメータ構造体
%
% 出力:
%   s   更新後の状態構造体
%       - s.Vd_ref    [V]  d軸電圧指令値（最終）
%       - s.Vq_ref    [V]  q軸電圧指令値（最終）
%
% データフロー:
%   s.iu_ad, s.iv_ad → [Clarke変換] → id_alpha, id_beta
%   → [Park変換 (theta_dq)] → s.id_ad, s.iq_ad
%   → [PI制御] → Vd_pi, Vq_pi
%   → [+ 非干渉補償] → s.Vd_ref, s.Vq_ref
%
% 呼び出し元:
%   im_vector_control_sim.m（PWM割込ごとに呼び出し）
% =========================================================================

% =========================================================================
% αβ→dq座標変換（Park変換）
% =========================================================================
% 目的: シミュレーションの3相電流（iu, iv, iw）を
%       dq回転座標系の電流（id_ad, iq_ad）に変換する。
%
% ステップ1: 3相 → αβ（Clarke変換）
%   ia = (2/3) * [iu - (iv + iw)/2]  → α成分（a軸 = U相方向）
%   ib = (2/3) * [√3/2 * (iv - iw)]  → β成分（α軸から90°）
%
%   ※振幅不変型 Clarke 変換（係数 2/3 を使用）

ia = (2.0/3.0) * (s.iu_ad - 0.5*(s.iv_ad + s.iw_ad));
ib = (2.0/3.0) * (sqrt(3.0)/2.0) * (s.iv_ad - s.iw_ad);

% ステップ2: αβ → dq（Park変換）
%   id = +cos(θ) * ia + sin(θ) * ib
%   iq = -sin(θ) * ia + cos(θ) * ib
%
% ここで θ = theta_dq（dq軸角度 = 一次角周波数の積分値）

s.id_ad =  s.cos_dq * ia + s.sin_dq * ib;
s.iq_ad = -s.sin_dq * ia + s.cos_dq * ib;

% =========================================================================
% d軸電流PIフィードバック制御
% =========================================================================
% 目的: d軸電流 id_ad を指令値 id_ref に追従させるための制御電圧 Vd_pi を生成する。
%
% PI制御則（連続時間、離散化はオイラー前進法）:
%   Vd_pi[k] = Kp_id * e_id[k] + Ki_id * Σ(e_id * Ts)
%   e_id[k] = id_ref[k] - id_ad[k]    （電流偏差）
%
% 組み込み:
%   e_id → Vd_ctrlp（比例項） + Vd_ctrli（積分項） → Vd_ctrl

% d軸電流偏差
e_id = s.id_ref - s.id_ad;

% 比例項
Vd_p = p.Kp_id * e_id;

% 積分項（前回値 + 偏差 × 積分ゲイン × 制御周期）
s.Vd_i = s.Vd_i + p.Ki_id * e_id * p.Ts_pwm;

% 積分項の出力制限（ワインドアップ防止）
s.Vd_i = max(-p.Vdq_ctrl_max, min(p.Vdq_ctrl_max, s.Vd_i));

% d軸PI制御出力（比例+積分）
Vd_pi = Vd_p + s.Vd_i;

% =========================================================================
% q軸電流PIフィードバック制御
% =========================================================================
% 目的: q軸電流 iq_ad を指令値 iq_ref に追従させる制御電圧 Vq_pi を生成する。
%
% d軸と同様の構造。

% q軸電流偏差
e_iq = s.iq_ref - s.iq_ad;

% 比例項
Vq_p = p.Kp_iq * e_iq;

% 積分項
s.Vq_i = s.Vq_i + p.Ki_iq * e_iq * p.Ts_pwm;

% 積分項の出力制限
s.Vq_i = max(-p.Vdq_ctrl_max, min(p.Vdq_ctrl_max, s.Vq_i));

% q軸PI制御出力
Vq_pi = Vq_p + s.Vq_i;

% =========================================================================
% 非干渉補償（デカップリング）電圧の演算
% =========================================================================
% 目的: dq軸間の干渉成分（速度起電力・逆起電力）をフィードフォワードで
%       キャンセルし、d軸・q軸を独立に制御できるようにする。
%
% 誘導モータのdq軸電圧方程式:
%   Vd = R1*id + Ls*d(id)/dt - ωe * Ls * iq
%   Vq = R1*iq + Ls*d(iq)/dt + ωe * (Ls*id + Lm*id_ref)
%
% 非干渉補償項（フィードフォワード電圧）:
%   Vd_ff = -ωe * Ls * iq_ref          （q→d方向の干渉キャンセル）
%   Vq_ff = +ωe * (Ls * id_ref + Lm * id_ref)
%         = +ωe * (Ls + Lm) * id_ref    （d→q方向 + 逆起電力キャンセル）
%
% ここで ωe = s.winv_ref（一次角周波数）
%
% 組み込み: fi_pwm_inv0_idqctrl.c 内の非干渉補償演算

wr_e = s.winv_ref;   % 電気角速度 [rad/s]（コントローラが推定した一次角周波数）

% d軸非干渉補償電圧（q電流による干渉キャンセル）
Vd_ff = -wr_e * p.Ls * s.iq_ref;

% q軸非干渉補償電圧（d電流による干渉 + 逆起電力キャンセル）
% fd_ref = Lm * id_ref : 二次磁束指令
Vq_ff = wr_e * (p.Ls * s.id_ref + s.fd_ref);

% =========================================================================
% 最終電圧指令値の合成
% =========================================================================
% PI制御出力 + 非干渉補償 = 最終的な電圧指令

s.Vd_ref = Vd_pi + Vd_ff;
s.Vq_ref = Vq_pi + Vq_ff;

% =========================================================================
% 電圧ベクトル制限（最大出力電圧クランプ）
% =========================================================================
% |Vdq| = sqrt(Vd^2 + Vq^2) が制限値 Vdq_ctrl_max を超えた場合、
% ベクトルを比例縮小してクランプする。
%
% 組み込み: K_INV0_VDQ_VCTRL = 1.13 相当の処理

Vdq_norm = sqrt(s.Vd_ref^2 + s.Vq_ref^2);
Vdq_max  = p.Vdq_ctrl_max;

if Vdq_norm > Vdq_max
    % ベクトル長を最大値に制限
    scale = Vdq_max / Vdq_norm;
    s.Vd_ref = s.Vd_ref * scale;
    s.Vq_ref = s.Vq_ref * scale;
end

% =========================================================================
% 弱め磁束制御（電圧制限 PI 補正）
% =========================================================================
% 目的: 高速回転時に電圧が制限値を超えた場合、d軸電流指令を減少させて
%       磁束を弱め（弱め磁束）、出力電圧を制限値以内に収める。
%
% 電圧ベクトル偏差:
%   Vdq_err = |Vdq_norm| - Vdq_ctrl_max
%   → Vdq_norm が制限値を超えている場合のみ補正量を演算
%
% 補正量（PI制御）→ s.id_ref から減算（d軸電流を減少させて磁束を弱める）
%
% ※ 補正量は常に非負とすることで、id_ref が意図せず増加しないようにする。
%
% 組み込み: KP_INV0_VDQCTRL = 0.02, KI_INV0_VDQCTRL = 0.004

% 電圧ベクトル偏差（制限値に対する超過量）
Vdq_err = Vdq_norm - Vdq_max;

if Vdq_err > 0.0
    % 超過している場合: 積分項を正方向に蓄積（補正量を増やす方向）
    s.vdq_ctrli = s.vdq_ctrli + p.Ki_vdqctrl * Vdq_err * p.Ts_pwm;

    % 積分項の上限制限（過補正防止）
    s.vdq_ctrli = max(0.0, min(p.Idq_vdqctrl_max, s.vdq_ctrli));

    % 補正量 = 比例項 + 積分項（常に非負: id_refを減少させる方向のみ作用）
    vdq_correction = p.Kp_vdqctrl * Vdq_err + s.vdq_ctrli;
    vdq_correction = max(0.0, vdq_correction);  % 非負に制限

    % d軸電流指令から補正量を減算（磁束を弱める）
    s.id_ref = s.id_ref - vdq_correction;
    s.id_ref = max(0.0, min(p.Id_ref_max, s.id_ref));  % 範囲制限
else
    % 超過していない場合: 積分項をゆっくりリセット（アンチワインドアップ）
    s.vdq_ctrli = s.vdq_ctrli * 0.99;
    s.vdq_ctrli = max(0.0, s.vdq_ctrli);  % 非負を維持
end

end
