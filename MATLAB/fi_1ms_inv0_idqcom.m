function s = fi_1ms_inv0_idqcom(s, p)
% =========================================================================
% fi_1ms_inv0_idqcom.m
%
% 機能:
%   1msタスク: dq軸電流指令値の演算
%
%   組み込みソフトの fi_1ms_inv0_idqcom.c に対応するMATLAB版関数。
%   トルク指令（または電流・電力指令）を受け取り、
%   ベクトル制御用の d軸・q軸電流指令値（id_ref, iq_ref）を生成する。
%
%   処理内容:
%     1) トルク指令値のレートリミット処理
%     2) トルク→dq電流指令変換
%        - d軸電流（励磁成分）: id_ref = 固定値（Id_ref_min以上）
%        - q軸電流（トルク成分）: iq_ref = Tq_ref / (Pp * Lm * id_ref) * 2/3
%     3) dq電流ベクトル制限（最大値クランプ）
%     4) 二次磁束指令値の演算: fd_ref = Lm * id_ref
%
% 入力:
%   s   状態構造体（s.tq_ref, s.id_ref, s.iq_ref などを参照・更新）
%   p   パラメータ構造体（params_inv0 が返す構造体）
%
% 出力:
%   s   更新後の状態構造体
%       - s.id_ref    [A]  d軸電流指令値（励磁成分）
%       - s.iq_ref    [A]  q軸電流指令値（トルク成分）
%       - s.fd_ref    [Wb] 二次磁束指令値
%
% データフロー:
%   s.tq_ref (上位指令) → [レートリミット] → [Tq→idq変換] → s.id_ref, s.iq_ref
%
% 呼び出し元:
%   im_vector_control_sim.m (10PWM周期ごとに呼び出し)
% =========================================================================

% =========================================================================
% トルク指令値のレートリミット処理
% =========================================================================
% トルク指令値を急変させると電流・電圧が制限値を超える可能性があるため、
% 単位時間あたりの変化量を dtq_up [N·m/s] 以内に制限する。
%
% 組み込みでは f4_dtq_inv0_ref_up を使用。
% シミュレーションでは定数として設定。

dtq_up = 200.0;    % トルク指令変化率制限値 [N·m/s]

% 1msあたりの最大変化量 [N·m]
d_tq_max = dtq_up * p.Ts_1ms;

% 前回指令値からの偏差を計算
d_tq = s.tq_ref - s.tq_ref_tmp;

% 変化量を制限してトルク指令内部値を更新
if d_tq > d_tq_max
    s.tq_ref_tmp = s.tq_ref_tmp + d_tq_max;
elseif d_tq < -d_tq_max
    s.tq_ref_tmp = s.tq_ref_tmp - d_tq_max;
else
    s.tq_ref_tmp = s.tq_ref_tmp + d_tq;
end

% =========================================================================
% d軸電流指令値（励磁電流）の決定
% =========================================================================
% 誘導モータのベクトル制御では、d軸は磁束軸に一致させるため、
% d軸電流 id_ref = 励磁電流 = 二次磁束 / 励磁インダクタンス
%
% ここでは固定値（Id_ref_min）を使用する。
% 弱め磁束制御時は id_ref を減少させるが、
% 本シミュレーションでは基本領域（id_ref = Id_ref_min = 定数）を想定。

s.id_ref = p.Id_ref_min;    % d軸電流指令 [A]（励磁成分、最低励磁電流以上に固定）

% =========================================================================
% q軸電流指令値（トルク電流）の演算
% =========================================================================
% 誘導モータのトルク式:
%   Tq = (3/2) * Pp * Lm * id_r * iq
%      = (3/2) * Pp * Lm * id_ref * iq_ref  （ベクトル制御理想時: id_r = id_ref）
%
% これを iq_ref について解くと:
%   iq_ref = Tq_ref / ((3/2) * Pp * Lm * id_ref)
%          = Tq_ref * 2 / (3 * Pp * Lm * id_ref)

if abs(s.id_ref) > 0.01   % ゼロ割り防止（励磁電流がほぼゼロの場合はスキップ）
    s.iq_ref = s.tq_ref_tmp * 2.0 / (3.0 * p.Pp * p.Lm * s.id_ref);
else
    s.iq_ref = 0.0;
end

% =========================================================================
% dq電流ベクトル制限（最大電流クランプ）
% =========================================================================
% dq電流ベクトルの大きさ |idq| = sqrt(id^2 + iq^2) が Idq_max を超えないよう制限する。
%
% まずベクトル長を計算し、超えていれば比例縮小する。

idq_norm = sqrt(s.id_ref^2 + s.iq_ref^2);

if idq_norm > p.Idq_max
    % ベクトルを最大値に収まるよう比例縮小する
    scale = p.Idq_max / idq_norm;
    s.id_ref = s.id_ref * scale;
    s.iq_ref = s.iq_ref * scale;
end

% さらに id_ref の最小値クランプ（励磁電流は Id_ref_min 以上を確保）
s.id_ref = max(s.id_ref, p.Id_ref_min);

% =========================================================================
% 二次磁束指令値の演算
% =========================================================================
% 二次磁束 ψ_r = Lm * id_ref
% （ベクトル制御では d軸を二次磁束軸に一致させているため）
%
% 組み込み: f4_fd_inv0_ref = f4_lm_inv0 * f4_id_inv0_ref

s.fd_ref = p.Lm * s.id_ref;    % 二次磁束指令 [Wb]

end
