function s = fi_pwm_inv0_svctrl(s, p)
% =========================================================================
% fi_pwm_inv0_svctrl.m
%
% 機能:
%   PWM割込タスク: dq電圧指令値の座標変換・空間ベクトルPWM変調率演算
%
%   組み込みソフトの fi_pwm_inv0_svctrl.c に対応するMATLAB版関数。
%   dq軸電圧指令（Vd_ref, Vq_ref）を3相電圧（Vu, Vv, Vw）に変換し、
%   直流母線電圧で正規化してPWM変調率（mu, mv, mw）を算出する。
%   空間ベクトル変調（SVPWM）によりDCバス利用率を最大化する。
%
%   処理内容:
%     1) dq → αβ座標変換（逆Park変換）
%     2) αβ → 3相電圧変換（逆Clarke変換）
%     3) 3相変調率の計算（2/Vdc による正規化）
%     4) 空間ベクトル変調（SVPWM）のオフセット演算
%        → 変調率の最大値と最小値の中点を引くことで、
%          直流母線利用率を √3/√2 ≈ 1.15倍向上させる
%     5) 変調率クランプ
%
% 入力:
%   s   状態構造体（s.Vd_ref, s.Vq_ref, s.theta_dq などを参照）
%   p   パラメータ構造体
%
% 出力:
%   s   更新後の状態構造体
%       - s.Va_ref    [V]  α軸電圧指令値
%       - s.Vb_ref    [V]  β軸電圧指令値
%       - s.Vu        [V]  U相電圧指令値
%       - s.Vv        [V]  V相電圧指令値
%       - s.Vw        [V]  W相電圧指令値
%       - s.mu        [-]  U相PWM変調率（-1〜+1）
%       - s.mv        [-]  V相PWM変調率
%       - s.mw        [-]  W相PWM変調率
%
% データフロー:
%   s.Vd_ref, s.Vq_ref → [逆Park変換] → Va, Vb
%   → [逆Clarke変換] → Vu, Vv, Vw
%   → [SVPWM変調] → mu, mv, mw
%
% 呼び出し元:
%   im_vector_control_sim.m（PWM割込ごとに呼び出し）
% =========================================================================

% =========================================================================
% dq → αβ座標変換（逆Park変換）
% =========================================================================
% 目的: 制御演算で求めたdq軸電圧指令を静止座標系（αβ）の電圧に変換する。
%
% 逆Park変換:
%   Va = cos(θ)*Vd - sin(θ)*Vq
%   Vb = sin(θ)*Vd + cos(θ)*Vq
%
% ここで θ = s.theta_dq（fi_pwm_inv0_encctrl が更新したdq軸角度）
%
% 組み込み:
%   f4_va_inv0_ref = cos_wt * Vd - sin_wt * Vq
%   f4_vb_inv0_ref = sin_wt * Vd + cos_wt * Vq

Va = s.cos_dq * s.Vd_ref - s.sin_dq * s.Vq_ref;   % α軸電圧 [V]
Vb = s.sin_dq * s.Vd_ref + s.cos_dq * s.Vq_ref;   % β軸電圧 [V]

s.Va_ref = Va;
s.Vb_ref = Vb;

% =========================================================================
% αβ → 3相電圧変換（逆Clarke変換）
% =========================================================================
% 目的: αβ電圧をU, V, W の3相電圧に変換する。
%
% 振幅不変型 逆Clarke変換:
%   Vu = (2/3) * Va
%   Vv = (2/3) * (-Va/2 + √3/2 * Vb)
%   Vw = (2/3) * (-Va/2 - √3/2 * Vb)
%
% 組み込み（係数確認）:
%   Vu = Va * 0.816496581              (= Va * √(2/3))
%   Vv = Va * (-0.40824829) + Vb * 0.70710678
%   Vw = Va * (-0.40824829) - Vb * 0.70710678
%
% ※ 組み込みでは √(2/3) = 0.8165 の係数を使用（振幅不変型）

s.Vu = Va * 0.816496581;
s.Vv = Va * (-0.40824829) + Vb * 0.70710678;
s.Vw = Va * (-0.40824829) - Vb * 0.70710678;

% =========================================================================
% 3相変調率の計算（DCバス電圧で正規化）
% =========================================================================
% 目的: 3相電圧指令値を直流母線電圧で正規化して変調率（-1〜+1の無次元値）に変換する。
%
% 変調率定義:
%   m = 2 * V_相 / Vdc    （-1 〜 +1）
%
% 例: Vdc = 800V、V相 = 400V → m = 2 * 400 / 800 = 1.0
%
% 組み込み:
%   f4_mu_tmp = 2.0 * Vu * (1/Vdc)

mu_tmp = 2.0 * s.Vu * p.dVdc;   % U相変調率（空間ベクトル補正前）
mv_tmp = 2.0 * s.Vv * p.dVdc;   % V相変調率
mw_tmp = 2.0 * s.Vw * p.dVdc;   % W相変調率

% =========================================================================
% 空間ベクトルPWM（SVPWM）オフセット演算
% =========================================================================
% 目的: 3相変調率の最大値・最小値の中点を引くことで、
%       直流母線利用率を正弦波PWMより向上させる（√3/√2 ≈ 1.15倍）。
%
% アルゴリズム:
%   1) max(mu, mv, mw) と min(mu, mv, mw) を求める
%   2) オフセット = (max + min) / 2
%   3) 各変調率からオフセットを引く → 3相の和がゼロになる
%
% これにより「零ベクトル区間を最大限活用するSVPWM」が実現される。
%
% 組み込み: fi_pwm_inv0_svctrl.c 内の空間ベクトル変調演算

% 最大値・最小値の探索
m_max = max([mu_tmp, mv_tmp, mw_tmp]);
m_min = min([mu_tmp, mv_tmp, mw_tmp]);

% 中点オフセット（3相の直流バイアス成分）
m_offset = (m_max + m_min) * 0.5;

% オフセットを差し引いたSVPWM変調率
s.mu = mu_tmp - m_offset;
s.mv = mv_tmp - m_offset;
s.mw = mw_tmp - m_offset;

% =========================================================================
% 変調率クランプ
% =========================================================================
% 過変調や電圧飽和によって変調率が制限値を超えないよう制限する。
%
% 組み込み: M_INV0_MAX = 1.10

s.mu = max(-p.M_max, min(p.M_max, s.mu));
s.mv = max(-p.M_max, min(p.M_max, s.mv));
s.mw = max(-p.M_max, min(p.M_max, s.mw));

end
