%==========================================================================
% im_vector_control_sim.m
%
% 誘導モータ（IM）ベクトル制御シミュレーション
%
% 目的:
%   本スクリプトは、組み込みソフトウェア（RH850/C1M 用 PE1 実装）に記述されている
%   誘導モータ（Induction Motor: IM）のベクトル制御アルゴリズムを MATLAB 上で
%   再現し、制御応答の確認・パラメータ調整を行うことを目的とする。
%
% 対応する組み込みソフトウェアファイル（参考）:
%   - fi_1ms_inv0_idqcom.c   : 1ms タスク / d-q 軸電流指令値演算
%   - fi_pwm_inv0_idqctrl.c  : PWM タスク / d-q 軸電流 PI 制御・電圧指令
%   - fi_pwm_inv0_svctrl.c   : PWM タスク / 空間ベクトル PWM（SVPWM）演算
%   - fi_pwm_inv0_syncctrl.c : PWM タスク / 同期角（磁束位相）更新
%   - mapdata_trq_inv0_map.c : トルクマップ（id/iq 指令値の補間テーブル）
%   - mapdata_lm_inv0_1d_map.c : 励磁インダクタンス Lm マップ（1次元）
%
% 制御構造（デュアルレート）:
%   本シミュレーションは、組み込みソフトと同様に「2 種類の演算周期」を模倣する。
%     [低速タスク: 1 ms]
%       - トルク指令値（f4_tq_inv0_ref）の制限・レートリミット処理
%       - トルクマップ補間による d-q 軸電流指令値（id_ref, iq_ref）の演算
%       - 出力制限（温度デレーティング）の反映
%     [高速タスク: 100 µs（PWM 割り込み相当）]
%       - d-q 軸電流フィードバック PI 制御
%       - 座標変換（dq → αβ → UVW）
%       - SVPWM デューティ計算
%       - 電動機プラントモデル（電圧→電流→トルク）の更新
%
% プラントモデルについて:
%   組み込みソフト側は「実機」を制御するため、プラントモデルは持たない。
%   本シミュレーションでは、誘導モータの電気回路を一次遅れ近似で模倣する。
%   この近似は厳密な状態方程式モデルではなく、主にゲイン確認・安定性評価を
%   目的とした「簡易プラント」である。
%
% 磁束・温度補正について:
%   - 励磁インダクタンス Lm は d 軸電流（id）に応じて 1 次元マップから補間する。
%     この処理は組み込みソフトの mapdata_lm_inv0_1d_map.c に対応する。
%   - 一次抵抗（Rs = r1）・二次抵抗（Rr = r2）の温度補正は、
%     組み込みソフトの u1_flag_enable_inv0_r1_cmp / r2_cmp フラグに相当する
%     スカラー係数として簡略化している。実機では推定温度から補正係数を計算するが、
%     本モデルでは固定値を使用する（将来的に可変化できるよう変数として定義）。
%
% トルクマップについて:
%   組み込みソフトでは 3 次元マップ（トルク指令・回転数・DCリンク電圧 の各軸）を
%   参照して id_ref / iq_ref を取得する。
%   本 MATLAB 版では、マップデータを簡略な 1 次元近似として実装しており、
%   本来の 3 次元補間よりも精度は低い。実機との一致度向上には別途マップデータの
%   移植が必要である。
%
% 使い方:
%   MATLAB コマンドウィンドウで以下を実行:
%     >> im_vector_control_sim
%   結果は変数 log および各グラフとして出力される。
%
% 注意:
%   本スクリプトは MATLAB R2021a 以降を想定している。
%   Simulink は不要（純粋な m スクリプト）。
%
% 作成日: 2024年8月
%==========================================================================

clear; close all; clc;

fprintf('=== 誘導モータ ベクトル制御シミュレーション 開始 ===\n');

%==========================================================================
%% [セクション1] モータ定格パラメータの定義
%
% 以下のパラメータは、組み込みソフトの fim_user_inv0.h / fi_pwm_inv0_idqctrl.c に
% 定義されている定数・設定値に対応している。
% 単位はすべて SI 単位系（Ω, H, Nm, rad/s など）。
%==========================================================================

% --- 極対数 ---
% 組み込み変数: p（fi_pwm_inv0_idqctrl.c 内で暗黙的に使用）
p  = 2;           % 極対数 [-]（例: 4 極機なら p=2）

% --- 一次抵抗（固定子抵抗: Rs）---
% 組み込み変数: f4_r1_inv0（モータ定格値）
Rs = 0.080;       % 一次抵抗 [Ω]（ノミナル値、温度補正なしの基準値）

% --- 二次抵抗（回転子抵抗: Rr）---
% 組み込み変数: f4_r2_inv0（モータ定格値）
Rr = 0.060;       % 二次抵抗 [Ω]（ノミナル値）

% --- 漏れインダクタンス（固定子側自己インダクタンスに相当）---
% 組み込み変数: f4_ls_inv0
Ls = 0.00025;     % 固定子インダクタンス [H]（漏れ成分含む）

% --- 励磁インダクタンス（基準値：マップで可変）---
% 組み込み変数: f4_lm_inv0_const（Lm の基準定数値）
% マップ補間後の動的値は f4_lm_inv0 に格納される（後のセクションで更新）
Lm_nom = 0.000211;  % 励磁インダクタンス ノミナル値 [H]（Lm マップの典型値）

% --- 慣性モーメント ---
J  = 0.003;       % ロータ慣性モーメント [kg·m²]

% --- 粘性摩擦係数 ---
B  = 0.001;       % 粘性摩擦 [N·m·s/rad]

% --- DC リンク電圧 ---
% 組み込み変数: f4_vdc_inv0（AD 計測値）
Vdc = 48.0;       % DC リンク電圧 [V]（48V 系システム想定）

%==========================================================================
%% [セクション2] 温度補正係数の定義（簡略化）
%
% 組み込みソフトでは、u1_flag_enable_inv0_r1_cmp / r2_cmp フラグが有効の場合、
% 推定温度に基づいて一次・二次抵抗を補正する（fi_pwm_inv0_idqctrl.c 参照）。
%
% 本シミュレーションでは、温度補正を「係数」として固定値で扱う簡略化を採用する。
% 将来的に可変化する場合は、これらの係数を時系列配列にすることで対応可能。
%
%   補正後抵抗値 = ノミナル抵抗値 × 補正係数
%     補正係数 = 1.0（補正なし）〜 典型的に 0.8〜1.4 程度（温度依存）
%==========================================================================

k_r1_cmp = 1.0;   % 一次抵抗 温度補正係数 [-]（1.0 = 補正なし）
k_r2_cmp = 1.0;   % 二次抵抗 温度補正係数 [-]（1.0 = 補正なし）

% 補正済み抵抗値（シミュレーション中は固定）
Rs_cmp = Rs * k_r1_cmp;  % 補正後一次抵抗 [Ω]
Rr_cmp = Rr * k_r2_cmp;  % 補正後二次抵抗 [Ω]

%==========================================================================
%% [セクション3] Lm マップデータの定義（1 次元補間テーブル）
%
% 組み込みソフト対応: mapdata_lm_inv0_1d_map.c
%
% 励磁インダクタンス Lm は d 軸電流（id）の大きさによって変化する。
% 実機では磁気飽和により、id が大きくなると Lm が低下する特性がある。
%
% 以下のテーブルは、実機マップデータの一部を抜粋・簡略化したものである。
% 軸（x 軸）: id [A]（d 軸電流の絶対値）
% 値（y 軸）: Lm [H]（対応する励磁インダクタンス）
%==========================================================================

% Lm マップ: x 軸（id [A]）
lm_map_id  = [0, 10, 20, 30, 40, 50, 60, 80, 100, 120, 150, 180, 200];

% Lm マップ: Lm [H]（実機データを参考にした近似値）
% id が大きいほど Lm が低下する磁気飽和特性を模擬している
lm_map_lm  = [0.000211, 0.000211, 0.000211, 0.000210, 0.000209, ...
              0.000208, 0.000206, 0.000202, 0.000196, 0.000188, ...
              0.000174, 0.000158, 0.000148];

%==========================================================================
%% [セクション4] トルクマップの定義（簡略化）
%
% 組み込みソフト対応: mapdata_trq_inv0_map.c
%
% 実機では、トルク指令（Te_ref）・回転数・DCリンク電圧を入力とする
% 3 次元ルックアップテーブルから id_ref / iq_ref を取得している。
%
% 本 MATLAB 版では、DCリンク電圧・回転数依存を無視し、
% トルク指令のみに基づく 1 次元近似マップとして実装する。
% これは「低速・定格電圧」付近での動作を近似したものであり、
% 高速領域・電圧変動に対する精度は低い点に注意すること。
%
% 軸: Te_ref [N·m]（トルク指令）
% 値: [id_ref, iq_ref] [A]（対応する d-q 軸電流指令値）
%
% 値のスケール: 実機マップデータ（整数値 / 100 = A 換算と仮定）
%==========================================================================

% トルクマップ: x 軸（トルク指令 [N·m]）
tq_map_x = [-80, -60, -40, -20, -10, 0, 10, 20, 40, 60, 80];

% トルクマップ: id_ref [A]（d 軸電流指令値）
% トルクの絶対値に応じて増加する（弱め磁束制御の最適電流）
tq_map_id = [6.80, 5.98, 4.61, 2.75, 1.78, 1.19, 1.78, 2.75, 4.61, 5.98, 6.80];

% トルクマップ: iq_ref [A]（q 軸電流指令値）
% トルクの符号と大きさに応じたトルク電流（負値 = 負トルク）
tq_map_iq = [-4.82, -3.34, -1.93, -0.95, -0.47, 0.02, 0.47, 0.95, 1.93, 3.34, 4.82];

%==========================================================================
%% [セクション5] PI 制御ゲインの定義
%
% 組み込みソフト対応: fi_pwm_inv0_idqctrl.c の以下の変数に相当
%   f4_kp_inv0_vdqctrl : 電流 PI 制御 比例ゲイン
%   f4_ki_inv0_vdqctrl : 電流 PI 制御 積分ゲイン
%
% 本シミュレーションでは d 軸・q 軸に同一ゲインを使用する（実機も同様の場合が多い）。
%==========================================================================

Kp_id = 0.5;    % d 軸電流 PI 制御 比例ゲイン [V/A]
Ki_id = 50.0;   % d 軸電流 PI 制御 積分ゲイン [V/(A·s)]
Kp_iq = 0.5;    % q 軸電流 PI 制御 比例ゲイン [V/A]
Ki_iq = 50.0;   % q 軸電流 PI 制御 積分ゲイン [V/(A·s)]

% 電圧指令値の飽和制限（DC リンク電圧の線形変調率から算出）
% 最大出力電圧振幅 = Vdc / sqrt(3)（SVPWM 最大変調時の線間電圧ピーク相当）
V_max = Vdc / sqrt(3);  % 電圧指令最大値 [V]

%==========================================================================
%% [セクション6] シミュレーション時間設定とデュアルレート周期の定義
%
% 組み込みソフトのタスク構造に対応:
%   低速タスク（1ms ティック）   : fi_1ms_inv0_idqcom.c など
%   高速タスク（100µs PWM 割り込み): fi_pwm_inv0_idqctrl.c / svctrl.c など
%
% 本シミュレーションでは高速タスク周期 dt_fast でループを回し、
% 低速タスク処理は (n_slow の倍数ステップ) のみ実行する。
%==========================================================================

dt_fast   = 100e-6;    % 高速タスク（PWM 周期相当）[s]
dt_slow   = 1e-3;      % 低速タスク（1ms タスク相当）[s]
n_slow    = round(dt_slow / dt_fast);  % 低速タスクを実行する高速ステップ数 [-]

t_end     = 0.5;       % シミュレーション終了時間 [s]
t         = 0 : dt_fast : t_end;  % 時間軸ベクトル
N         = length(t);             % 総ステップ数

%==========================================================================
%% [セクション7] トルク指令プロファイルの設定
%
% 組み込みソフト対応: f4_tq_inv0_ref（ユーザ設定値）
%
% ここでは、シミュレーション中にトルク指令をステップ状に変化させる
% 入力プロファイルを定義する。実機では外部コントローラ（上位 ECU）や
% ユーザ設定から入力される値に相当する。
%==========================================================================

Te_ref_profile = zeros(1, N);  % トルク指令プロファイル [N·m]

% 0.05 s: 正方向ステップ（+30 N·m）
Te_ref_profile(t >= 0.05) = 30.0;

% 0.20 s: 負方向ステップ（-20 N·m）
Te_ref_profile(t >= 0.20) = -20.0;

% 0.35 s: ゼロに戻す（0 N·m）
Te_ref_profile(t >= 0.35) = 0.0;

%==========================================================================
%% [セクション8] 状態変数の初期化
%
% 以下の変数はシミュレーション中に各ステップで更新される状態量である。
% 対応する組み込みソフト変数名をコメントに記載する。
%==========================================================================

% --- 電流フィードバック値 ---
id_meas = 0;   % d 軸電流 計測値 [A]  （組み込み: f4_id_inv0_ad）
iq_meas = 0;   % q 軸電流 計測値 [A]  （組み込み: f4_iq_inv0_ad）

% --- 電流指令値（低速タスクから高速タスクへ受け渡す変数）---
id_ref  = 0;   % d 軸電流 指令値 [A]  （組み込み: f4_id_inv0_ctrl）
iq_ref  = 0;   % q 軸電流 指令値 [A]  （組み込み: f4_iq_inv0_ctrl）

% --- PI 制御の積分項（ウィンドアップ防止のためクランプが必要）---
int_id  = 0;   % d 軸電流 PI 積分器状態 [V]
int_iq  = 0;   % q 軸電流 PI 積分器状態 [V]

% --- 電圧指令値 ---
Vd_ref  = 0;   % d 軸電圧 指令値 [V]  （組み込み: f4_vd_inv0_ref）
Vq_ref  = 0;   % q 軸電圧 指令値 [V]  （組み込み: f4_vq_inv0_ref）

% --- 磁束位相角（同期角）---
% 組み込みソフト対応: fi_pwm_inv0_syncctrl.c の f4_wt_inv0_svctrl
theta   = 0;   % 同期角（磁束位相角）[rad]

% --- 角速度（回転子機械角速度）---
omega_r = 0;   % 回転子角速度 [rad/s]  （組み込み: f4_wr_inv0 または速度フィードバック）

% --- すべり角速度 ---
omega_s = 0;   % すべり角速度 [rad/s]  （組み込み: 内部演算値）

% --- 励磁インダクタンス（マップ補間後の動的値）---
% 組み込み変数: f4_lm_inv0
Lm      = Lm_nom;  % Lm 初期値（ノミナル値）

% --- 発生トルク ---
Te      = 0;   % 発生トルク（推定値）[N·m]  （組み込み: f4_tq_inv0_est）

% --- トルク指令（レートリミット後の値）---
% 組み込み変数: f4_tq_inv0_ref_tmp
Te_ref_tmp = 0;  % トルク指令のレートリミット済み値 [N·m]

%==========================================================================
%% [セクション9] トルク指令レートリミット設定
%
% 組み込みソフト対応: fi_1ms_inv0_idqcom.c の f4_dtq_inv0_ref_up
%
% 急激なトルク変化を防ぐため、1ms タスクでトルク指令値にレートリミッタを適用する。
% 単位: [N·m / ms] = [kN·m/s]（1ms 単位での変化量制限）
%==========================================================================

dTe_max = 5.0;   % トルク指令レートリミット [N·m/ms]（1ms タスク 1 回あたりの最大変化量）

%==========================================================================
%% [セクション10] ログ用配列の確保
%
% シミュレーション結果を各ステップ記録するための配列を事前確保する。
% 事前確保することで MATLAB のループ中の動的メモリ確保を避け、実行速度を向上させる。
%==========================================================================

log_t       = zeros(1, N);   % 時間 [s]
log_Te      = zeros(1, N);   % 発生トルク [N·m]
log_Te_ref  = zeros(1, N);   % トルク指令値 [N·m]
log_id      = zeros(1, N);   % d 軸電流 [A]
log_iq      = zeros(1, N);   % q 軸電流 [A]
log_id_ref  = zeros(1, N);   % d 軸電流 指令値 [A]
log_iq_ref  = zeros(1, N);   % q 軸電流 指令値 [A]
log_omega_r = zeros(1, N);   % 回転子角速度 [rad/s]
log_Vd      = zeros(1, N);   % d 軸電圧 指令値 [V]
log_Vq      = zeros(1, N);   % q 軸電圧 指令値 [V]
log_Lm      = zeros(1, N);   % 励磁インダクタンス [H]
log_theta   = zeros(1, N);   % 同期角 [rad]

%==========================================================================
%% [セクション11] メインシミュレーションループ
%
% 各ステップで以下の処理を順番に実行する（組み込みソフトのタスク順に準拠）:
%
%   [低速タスク: n_slow ステップごとに実行]
%     1) トルク指令のレートリミット処理
%     2) トルクマップ補間による id_ref / iq_ref 演算
%        （対応: fi_1ms_inv0_idqcom.c）
%
%   [高速タスク: 毎ステップ実行]
%     3) 励磁インダクタンス Lm のマップ更新
%        （対応: mapdata_lm_inv0_1d_map.c）
%     4) すべり角速度の演算
%        （対応: fi_pwm_inv0_syncctrl.c の slip 演算部）
%     5) 同期角（磁束位相角）の積分更新
%        （対応: fi_pwm_inv0_syncctrl.c の theta 更新部）
%     6) d-q 軸電流 PI 制御（電圧指令値の演算）
%        （対応: fi_pwm_inv0_idqctrl.c）
%     7) 電圧指令値の飽和クランプ
%        （対応: fi_pwm_inv0_idqctrl.c の f4_idq_inv0_vdqctrl_max 相当）
%     8) プラントモデル（電流応答）の更新
%        （組み込みソフトには対応なし：MATLAB シミュレーション専用）
%     9) 発生トルクの推定演算
%        （対応: fi_1ms_inv0_idqcom.c の f4_tq_inv0_est 演算）
%    10) 機械系（回転子速度）の更新
%        （組み込みソフトには対応なし：MATLAB シミュレーション専用）
%    11) ログへの記録
%==========================================================================

for n = 1 : N

    %----------------------------------------------------------------------
    % [低速タスク処理] 1ms タスク相当
    % 組み込みソフト: fi_1ms_inv0_idqcom.c
    % n_slow ステップ（= 10 ステップ）に 1 回だけ実行する
    %----------------------------------------------------------------------
    if mod(n-1, n_slow) == 0

        % ------------------------------------------------------------------
        % [低速1] トルク指令値のレートリミット処理
        %
        % 組み込み変数:
        %   f4_tq_inv0_ref     : ユーザ設定トルク指令値
        %   f4_tq_inv0_ref_tmp : レートリミット後の一時値
        %   f4_dtq_inv0_ref_up : 1ms あたりの変化量制限
        %
        % 急激なトルク変化を防ぐため、前回値からの変化量を dTe_max 以内に制限する。
        % これにより電流の急変を抑制し、過電流保護に貢献する。
        % ------------------------------------------------------------------
        Te_ref_in = Te_ref_profile(n);  % 今回の入力トルク指令値
        delta_Te  = Te_ref_in - Te_ref_tmp;  % 前回値からの偏差

        % 変化量を ±dTe_max に制限（レートリミッタ）
        if delta_Te > dTe_max
            delta_Te = dTe_max;
        elseif delta_Te < -dTe_max
            delta_Te = -dTe_max;
        end
        Te_ref_tmp = Te_ref_tmp + delta_Te;  % レートリミット後のトルク指令値を更新

        % ------------------------------------------------------------------
        % [低速2] トルクマップ補間による id_ref / iq_ref の演算
        %
        % 組み込みソフト対応: fi_1ms_inv0_idqcom.c の u1_flag_mode_inv0_idqcom = 1
        %   （トルクマップモード）
        % 組み込み変数:
        %   f4_id_inv0_ctrl : d 軸電流指令値（1ms タスクが更新、PWM タスクが参照）
        %   f4_iq_inv0_ctrl : q 軸電流指令値（同上）
        %
        % 実機では 3 次元マップ（トルク×回転数×Vdc）を参照するが、
        % 本モデルではトルク指令のみの 1 次元近似を使用する。
        % ------------------------------------------------------------------
        id_ref = interp1(tq_map_x, tq_map_id, Te_ref_tmp, 'linear', 'extrap');
        iq_ref = interp1(tq_map_x, tq_map_iq, Te_ref_tmp, 'linear', 'extrap');

        % 電流指令値の安全制限（過電流防止）
        % 組み込みソフトの f4_id_inv0_ref_max / min 相当
        id_ref = max(0.5, min(id_ref, 30.0));  % id は正（励磁電流は正方向）
        iq_ref = max(-30.0, min(iq_ref, 30.0));

    end  % [低速タスク終了]

    %----------------------------------------------------------------------
    % [高速タスク処理] PWM 割り込み相当（毎ステップ実行）
    %----------------------------------------------------------------------

    % ------------------------------------------------------------------
    % [高速1] 励磁インダクタンス Lm のマップ更新
    %
    % 組み込みソフト対応: mapdata_lm_inv0_1d_map.c
    % 組み込み変数: f4_lm_inv0（マップ補間後の動的 Lm 値）
    %
    % d 軸電流（id_meas）の絶対値に基づき、磁気飽和を考慮した Lm を補間する。
    % id が大きくなると磁気飽和により Lm が低下する。
    % ------------------------------------------------------------------
    Lm = interp1(lm_map_id, lm_map_lm, abs(id_meas), 'linear', 'extrap');
    Lm = max(Lm, 1e-6);  % 数値的安定性のため下限値を設ける

    % ------------------------------------------------------------------
    % [高速2] すべり角速度（slip）の演算
    %
    % 組み込みソフト対応: fi_pwm_inv0_syncctrl.c 内のすべり演算部
    %
    % 誘導モータのベクトル制御では、回転子磁束方向に d 軸を合わせるため、
    % 「すべり」に相当する角速度を同期角に加算する必要がある。
    %
    % すべり角速度の近似式:
    %   omega_slip = (Rr / Lm) * (iq_ref / max(id_ref, 閾値))
    %
    % この式は、定常すべり条件（磁束一定制御）から導出される。
    % 分母の閾値（0.2 A）は、ゼロ近傍での数値発散を防ぐ保護処理であり、
    % 組み込みソフトでも同様のクランプ処理が存在する。
    % ------------------------------------------------------------------
    omega_slip = (Rr_cmp / Lm) * (iq_ref / max(id_ref, 0.2));

    % ------------------------------------------------------------------
    % [高速3] 同期角（磁束位相角 θ）の積分更新
    %
    % 組み込みソフト対応: fi_pwm_inv0_syncctrl.c の theta 更新処理
    % 組み込み変数: f4_wt_inv0_svctrl（SVPWM 用同期角）
    %
    % 同期角速度 = 回転子機械角速度 × 極対数 + すべり角速度
    % これをオイラー法で積分して位相角 theta を更新する。
    % theta は dq-αβ 座標変換（Park 変換）で使用される。
    % ------------------------------------------------------------------
    omega_sync = p * omega_r + omega_slip;  % 同期角速度 [rad/s]
    theta = theta + omega_sync * dt_fast;   % 位相角の積分（オイラー法）
    theta = mod(theta, 2*pi);               % 位相角を [0, 2π) に正規化

    % Park 変換用の sin/cos 値を事前計算（各ステップで再利用）
    % 組み込み変数: f4_sin_inv0_wtsvctrl / f4_cos_inv0_wtsvctrl
    sin_th = sin(theta);
    cos_th = cos(theta);

    % ------------------------------------------------------------------
    % [高速4] d-q 軸電流 PI 制御（電圧指令値の演算）
    %
    % 組み込みソフト対応: fi_pwm_inv0_idqctrl.c
    % 組み込み変数:
    %   f4_vd_inv0_ref : d 軸電圧指令値
    %   f4_vq_inv0_ref : q 軸電圧指令値
    %
    % d-q 軸それぞれに独立した PI 制御器を適用し、電流偏差をゼロに収束させる。
    % 非干渉化補償（非干渉項: -omega_sync*Ls*iq, +omega_sync*Ls*id）は
    % 現モデルでは省略している（将来的な追加が可能）。
    % ------------------------------------------------------------------

    % d 軸電流の偏差（指令値 - 計測値）
    err_id = id_ref - id_meas;

    % q 軸電流の偏差
    err_iq = iq_ref - iq_meas;

    % 積分項の更新（Euler 積分）
    int_id = int_id + Ki_id * err_id * dt_fast;
    int_iq = int_iq + Ki_iq * err_iq * dt_fast;

    % 積分項のクランプ（ワインドアップ防止）
    % 組み込みソフトでは積分出力が電圧指令範囲を超えないようにクランプしている
    int_id = max(-V_max, min(int_id, V_max));
    int_iq = max(-V_max, min(int_iq, V_max));

    % PI 出力（電圧指令値）
    Vd_ref = Kp_id * err_id + int_id;
    Vq_ref = Kp_iq * err_iq + int_iq;

    % ------------------------------------------------------------------
    % [高速5] 電圧指令値の飽和クランプ（電圧制限）
    %
    % 組み込みソフト対応: fi_pwm_inv0_idqctrl.c の f4_idq_inv0_vdqctrl_max 処理
    %
    % d 軸・q 軸の合成電圧振幅が V_max を超えないよう制限する。
    % SVPWM の最大変調度に相当する上限値（Vdc / sqrt(3)）でクランプ。
    % この処理は実機でも重要な過変調防止機能である。
    % ------------------------------------------------------------------
    Vdq_amp = sqrt(Vd_ref^2 + Vq_ref^2);  % 合成電圧振幅 [V]
    if Vdq_amp > V_max
        % 振幅方向を維持したままスケールダウン（ベクトル正規化）
        scale  = V_max / Vdq_amp;
        Vd_ref = Vd_ref * scale;
        Vq_ref = Vq_ref * scale;
    end

    % ------------------------------------------------------------------
    % [高速6] プラントモデル：電流応答の更新
    %
    % 【注意】この処理は組み込みソフトには存在しない。
    %         MATLAB シミュレーション専用のプラント（モータ）モデルである。
    %
    % 誘導モータの d-q 軸等価回路（簡略化一次遅れモデル）:
    %   d(id)/dt = (Vd - Rs*id + omega_sync*Ls*iq) / Ls
    %   d(iq)/dt = (Vq - Rs*iq - omega_sync*Ls*id) / Ls
    %
    % この式は、定常磁束仮定下での d-q 軸電圧方程式を離散化したものである。
    % 実際の誘導モータは磁束状態方程式と組み合わせた 4 次システムだが、
    % ここでは制御帯域内での応答確認を目的として 2 次に簡略化している。
    % ------------------------------------------------------------------

    % d 軸電流の微分（電圧方程式から）
    did_dt = (Vd_ref - Rs_cmp * id_meas + omega_sync * Ls * iq_meas) / Ls;

    % q 軸電流の微分
    diq_dt = (Vq_ref - Rs_cmp * iq_meas - omega_sync * Ls * id_meas) / Ls;

    % オイラー法で電流を更新
    id_meas = id_meas + did_dt * dt_fast;
    iq_meas = iq_meas + diq_dt * dt_fast;

    % ------------------------------------------------------------------
    % [高速7] 発生トルクの推定演算
    %
    % 組み込みソフト対応: fi_1ms_inv0_idqcom.c の f4_tq_inv0_est
    %
    % 誘導モータのトルク推定式（簡略版）:
    %   Te = (3/2) * p * Lm * id_meas * iq_meas
    %
    % 厳密には回転子磁束を経由したトルク式を用いるべきだが、
    % 磁束一定制御（id = 一定）が成立している場合はこの近似が有効である。
    % 組み込みソフトでは電力（P = Vd*Id + Vq*Iq）からトルクを逆算する方法も使用。
    % ------------------------------------------------------------------
    Te = (3/2) * p * Lm * id_meas * iq_meas;  % 発生トルク推定値 [N·m]

    % ------------------------------------------------------------------
    % [高速8] 機械系（回転子速度）の更新
    %
    % 【注意】この処理も組み込みソフトには存在しない（MATLAB 専用プラント）。
    %
    % 運動方程式（Newton の第 2 法則のトルク版）:
    %   J * d(omega_r)/dt = Te - B * omega_r - TL
    %   ここで TL は負荷トルク（本モデルでは 0 として簡略化）
    % ------------------------------------------------------------------
    T_load   = 0.0;  % 負荷トルク [N·m]（本モデルでは無負荷を仮定）
    domega_r = (Te - B * omega_r - T_load) / J;  % 角加速度 [rad/s²]
    omega_r  = omega_r + domega_r * dt_fast;      % 角速度を積分更新

    %----------------------------------------------------------------------
    % [ログ記録] 各ステップの状態量を保存
    %----------------------------------------------------------------------
    log_t(n)       = t(n);
    log_Te(n)      = Te;
    log_Te_ref(n)  = Te_ref_tmp;
    log_id(n)      = id_meas;
    log_iq(n)      = iq_meas;
    log_id_ref(n)  = id_ref;
    log_iq_ref(n)  = iq_ref;
    log_omega_r(n) = omega_r;
    log_Vd(n)      = Vd_ref;
    log_Vq(n)      = Vq_ref;
    log_Lm(n)      = Lm;
    log_theta(n)   = theta;

end  % メインループ終了

fprintf('=== シミュレーション完了 ===\n');

