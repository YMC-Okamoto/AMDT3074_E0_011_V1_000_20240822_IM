function p = params_inv0()
% =========================================================================
% params_inv0.m
%
% 機能:
%   誘導モータ（IM）ベクトル制御シミュレーション用パラメータを定義し、
%   構造体 p として返す。
%
%   組み込みソフトの fim_user_inv0.h に対応するMATLAB版パラメータファイル。
%   シミュレーション固有の追加パラメータ（慣性モーメント等）も含む。
%
% 出力:
%   p   パラメータ構造体（全モジュール共通）
%
% 呼び出し元:
%   im_vector_control_sim.m
%
% 更新履歴:
%   - 初版作成
% =========================================================================

% =========================================================================
% システム基本設定
% =========================================================================

% PWMキャリア周波数 [Hz]  (組み込み: FC_PWM_INV0 = 10000)
p.Fc_pwm    = 10000;

% PWMサンプリング周期 [s] (= 1/Fc_pwm = 100 µs)
p.Ts_pwm    = 1.0 / p.Fc_pwm;

% 1msタスク周期 [s]
% PWM割込 10回に1回、1msタスクを実行する
p.Ts_1ms    = 0.001;

% 1msタスクの間引き比 [-]  (= Ts_1ms / Ts_pwm = 10)
p.N_1ms     = round(p.Ts_1ms / p.Ts_pwm);

% =========================================================================
% モータ基本パラメータ
% =========================================================================

% 極対数 [-]  (組み込み: PF_INV0 = 2)
p.Pp        = 2.0;

% 一次抵抗 [Ω]  (組み込み: R1_INV0 = 0.0044)
p.R1        = 0.0044;

% 二次抵抗 [Ω]  (組み込み: R2_INV0 = 0.0023)
% ※ 漏れインダクタンスが一次側にまとめられているため r2 = r1 として扱う
p.R2        = 0.0023;

% 漏れインダクタンス [H]  (組み込み: LS_INV0 = 0.00005)
% ※ 一次側漏れと二次側漏れをまとめた等価値
p.Ls        = 0.00005;

% 励磁インダクタンス [H]  (組み込み: LM_INV0 = 0.00021)
p.Lm        = 0.00021;

% 二次抵抗の温度補正基準温度 [℃]  (組み込み: TMP_INV0_R2 = 25.6)
p.Tmp_R2_base = 25.6;

% =========================================================================
% 電流制限値
% =========================================================================

% dq電流ベクトル最大値 [A]  (組み込み: IDQ_INV0_MAX = 10.0*1.732)
p.Idq_max   = 10.0 * 1.732;

% d軸電流指令最小値 [A]  (組み込み: ID_INV0_REF_MIN = 3.0)
% 励磁電流を最低限この値以上に保持する
p.Id_ref_min = 3.0;

% d軸電流指令最大値 [A]  (= Idq_max)
p.Id_ref_max = p.Idq_max;

% =========================================================================
% すべり周波数制限
% =========================================================================

% すべり周波数最大値 [Hz]  (組み込み: FSL_INV0_REF_MAX = 20.0)
p.Fsl_max   = 20.0;

% すべり角周波数最大値 [rad/s]  (= 2π * Fsl_max)
p.Wsl_max   = 2.0 * pi * p.Fsl_max;

% =========================================================================
% DC電圧
% =========================================================================

% 直流母線電圧 [V]  (シミュレーション用固定値)
p.Vdc       = 800.0;

% 1/Vdc  [1/V]  (演算用逆数)
p.dVdc      = 1.0 / p.Vdc;

% =========================================================================
% dq電流PIフィードバック制御ゲイン
% =========================================================================
% 組み込み: KP_INV0_IDQ_CTRL_MAX = 0.10, KI_INV0_IDQ_CTRL_MAX = 0.1
%
% 設計指針:
%   電流制御帯域 ωc = 2000 rad/s (≈ 318 Hz) として
%     Kp = Ls * ωc = 0.00005 * 2000 = 0.10 [V/A]
%     Ki = R1 * ωc = 0.0044 * 2000 = 8.8  [V/(A·s)]
%
%   ※組み込みでは変調率に応じてゲインを可変にしているが、
%     シミュレーションでは一定値を使用する。
% =========================================================================

% d軸電流制御 比例ゲイン [V/A]
p.Kp_id     = 0.10;

% d軸電流制御 積分ゲイン [V/(A·s)]
p.Ki_id     = 8.8;

% q軸電流制御 比例ゲイン [V/A]
p.Kp_iq     = 0.10;

% q軸電流制御 積分ゲイン [V/(A·s)]
p.Ki_iq     = 8.8;

% dq電流PI制御 出力電圧制限値 [V]
% (組み込み: K_INV0_VDQ_VCTRL = 1.13 → Vdq_max = 1.13 * Vdc/√3)
p.Vdq_ctrl_max = 1.13 * p.Vdc / sqrt(3.0);

% =========================================================================
% 弱め磁束制御ゲイン（電圧制限PI制御）
% =========================================================================
% 組み込み: KP_INV0_VDQCTRL = 0.02, KI_INV0_VDQCTRL = 0.004

% 弱め磁束PI 比例ゲイン [-]
p.Kp_vdqctrl = 0.02;

% 弱め磁束PI 積分ゲイン [-]
p.Ki_vdqctrl = 0.004;

% 弱め磁束PI 出力制限値 [A]  (= IDQ_max * 0.7)
p.Idq_vdqctrl_max = p.Idq_max * 0.7;

% =========================================================================
% 速度推定PLL（エンコーダ）ゲイン
% =========================================================================
% 組み込み: KP_INV0_WRPLL = 1000, KI_INV0_WRPLL = 10000
%            WCLPF_INV0_WRPLL = 800 [rad/s]
%            WR_INV0_PLL_MAX = 20000 [-]

% PLL 比例ゲイン [-]
p.Kp_wrpll  = 1000.0;

% PLL 積分ゲイン [-]
p.Ki_wrpll  = 10000.0;

% PLL 速度出力LPFカットオフ角周波数 [rad/s]
p.Wclpf_wrpll = 800.0;

% PLL 速度推定上限値 [rad/s]
p.Wr_pll_max = 20000.0;

% =========================================================================
% 変調率制限
% =========================================================================

% インバータ変調率最大値 [-]  (組み込み: M_INV0_MAX = 1.10)
p.M_max     = 1.10;

% =========================================================================
% エンコーダ設定
% =========================================================================

% エンコーダ最大カウント値 [-]  (組み込み: CNT_ENC0_MAX = 255)
% 1回転で0〜CNT_ENC0_MAX のカウント値をとる
p.Cnt_enc_max = 255;

% センサ極数比 [-]  (組み込み: MOT_INV0_REZO_POLE = 2.0)
% センサの極数 / モータの極数
p.Rezo_pole = 2.0;

% =========================================================================
% シミュレーション専用パラメータ
% =========================================================================

% 回転子慣性モーメント [kg·m²]
% ※ 実機パラメータ非公開のため推定値を使用
p.J         = 0.005;

% 負荷トルク [N·m]  (定常負荷)
% ※ 実運転条件に合わせて調整する
p.Tload     = 5.0;

% =========================================================================
% 数学定数
% =========================================================================

% 2π
p.TWOPI     = 2.0 * pi;

% 1/2π
p.dTWOPI    = 1.0 / (2.0 * pi);

end
