function s = plant_model_im(s, p, Ts)
% plant_model_im
% 誘導電動機の簡略プラントモデル（シミュレーション専用）
%
% 【重要】
% この関数は「組み込み実機コード」ではありません。
% シミュレーションで制御ループを閉じるために、実機の代わりとして
% モータの電気・機械挙動を簡略式で近似計算するモデルです。
%
% 【この関数の目的】
% コントローラが出力した dq電圧指令（vd_ref, vq_ref）を入力として、
% 次周期の電流・速度・角度を更新し、制御器へフィードバックします。
%
% 【採用している主な仮定（簡略化）】
% 1) 回転子磁束指向（Rotor-flux oriented）を前提
%    fd = Lm*id, fq = 0 の標準的な間接ベクトル制御の近似
% 2) 動作点近傍で線形化した電気方程式
% 3) 機械系は 1自由度モデル
%    J * dω/dt = Te - Tload
% 4) 粘性摩擦、鉄損、クロスサチュレーション等は無視
% 5) DCバスは理想電源（一定）扱い
%
% 【この関数で更新する主な状態】
%   s.id_meas, s.iq_meas   : dq電流（プラント出力）
%   s.omega_mech           : 機械角速度 [rad/s]
%   s.theta_mech           : 機械角 [rad]
%   s.speed_mech_rpm       : 機械回転数 [rpm]
%   s.tq_plant             : 電磁トルク [Nm]
%
% 【使用する主なパラメータ】
%   s.r1_cmp, s.r2_cmp, s.lm, p.LS_INV0, p.PF_INV0, s.J
%
% 【組み込み対応】
% 直接対応する組み込み関数はありません（SIM専用）。

    % ---------------------------------------------------------------
    % 0) モータ・機械パラメータの取り出し
    % ---------------------------------------------------------------
    R1 = s.r1_cmp;    % [Ω] 一次抵抗（温度補正後）
    R2 = s.r2_cmp;    % [Ω] 二次抵抗（温度補正後）※本簡略式では直接未使用
    Lm = s.lm;        % [H] 励磁インダクタンス
    Ls = p.LS_INV0;   % [H] 漏れインダクタンス相当
    pf = p.PF_INV0;   % 極対数
    J  = s.J;         % [kg·m^2] 慣性モーメント

    % 制御器が前段で計算した dq軸電圧指令
    vd = s.vd_ref;
    vq = s.vq_ref;

    % 同期角速度（ここではインバータ電気角速度を使用）
    winv = s.winv_ref;

    % ---------------------------------------------------------------
    % 1) 電気系状態方程式（同期dq座標）
    % ---------------------------------------------------------------
    % 簡略誘導機モデル:
    %   vd = R1*id + Ls*d(id)/dt - winv*Ls*iq
    %   vq = R1*iq + Ls*d(iq)/dt + winv*(Ls*id + Lm*id)
    %      = R1*iq + Ls*d(iq)/dt + winv*(Ls+Lm)*id
    %
    % これを d(id)/dt, d(iq)/dt について解いて、オイラー積分で更新します。
    did_dt = (vd - R1*s.id_meas + winv*Ls*s.iq_meas) / Ls;
    diq_dt = (vq - R1*s.iq_meas - winv*(Ls + Lm)*s.id_meas) / Ls;

    % 離散時間更新（前進オイラー）
    s.id_meas = s.id_meas + did_dt * Ts;
    s.iq_meas = s.iq_meas + diq_dt * Ts;

    % ---------------------------------------------------------------
    % 2) 電磁トルク計算
    % ---------------------------------------------------------------
    % 誘導機の簡易トルク式（回転子磁束指向前提）:
    %   Te = (3/2) * pf * Lm * id * iq
    s.tq_plant = (3/2) * pf * Lm * s.id_meas * s.iq_meas;

    % ---------------------------------------------------------------
    % 3) 機械系更新
    % ---------------------------------------------------------------
    % 機械運動方程式（粘性項なし）:
    %   J * dω/dt = Te - Tload
    domega = (s.tq_plant - s.tq_load) / J;
    s.omega_mech = s.omega_mech + domega * Ts;

    % 機械角を積分更新
    s.theta_mech = s.theta_mech + s.omega_mech * Ts;
    % 角度ラップ（-pi～pi）は encctrl 側で電気角として処理するため、ここでは未実施

    % ログや1msタスクで使いやすいように rpm も保持
    s.speed_mech_rpm = s.omega_mech * (60.0 / (2*pi));

    % R2 は現式では未使用ですが、将来モデル拡張（2次回路動特性追加等）を見据えて保持
    %#ok<NASGU>
end