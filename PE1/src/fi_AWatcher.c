/*===============================================================
+																+
+				Name:		void fi_awc_rx (void)				+
+			Function:		受信割込み処理						+
+																+
+					1)		各機能別関数の処理					+
+																+
+		Return Value:		No									+
+				date:		 29th May,2015						+
+																+
===============================================================*/
void fi_awc_rx (void)
{
	/*============================================================*/
	/*					割り込みを有効にする					　*/
	/*============================================================*/
	__EI();
	/*============================================================*/

	/*============================================================*/
	/*					Watcherデータ処理		　				  */
	/*============================================================*/
	VECLIB_CMDMONI_INTR();
	/*============================================================*/

	/*============================================================*/
	/*				割り込みを抜ける前に割り込み禁止する	　	  */
	/*============================================================*/	
	__DI();
	/*============================================================*/
}

/*===============================================================
+																+
+				Name:		void fi_awc_re (void)				+
+			Function:		受信エラー割込み処理				+
+																+
+					1)		AWatcher機能別関数の処理			+
+																+
+		Return Value:		No									+
+				date:		 29th May,2015						+
+																+
===============================================================*/
u4	u4_cnt_re_oer;
u4	u4_cnt_re_fer;
void fi_awc_re (void)
{
	if ( 1 == SCI30.SSR.BIT.ORER )
	{
		u4_cnt_re_oer++;
	}
	if ( 1 == SCI30.SSR.BIT.FER )
	{
		u4_cnt_re_fer++;
	}		
	/*============================================================*/
	/*					割り込みを有効にする					　*/
	/*============================================================*/
	__EI();
	/*============================================================*/

	/*============================================================*/
	/*					Watcherデータ処理		　				  */
	/*============================================================*/
	VECLIB_CMDMONI_INTRE();
	/*============================================================*/

	/*============================================================*/
	/*				割り込みを抜ける前に割り込み禁止する	　	  */
	/*============================================================*/	
	__DI();
	/*============================================================*/
}
