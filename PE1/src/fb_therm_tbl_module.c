/*=============================================================*/
/*	サーミスタ温度変換関数									   */
/*  引数範囲	0 ~ 1023									   */
/*  戻り値範囲　-327.68 ~ 327.67℃ * 100(lsb=1e-2)			   */
/*=============================================================*/
s2	s2_therm_module_calc_lsb2(u2 t_volt)
{
	u2	t_h7bit;
	u2	t_l3bit;
	s2	t_lower, t_upper, t_lcmp;
	
	t_h7bit	= (t_volt >> 3) & 0x7f ; 			/* 上位7ビット	*/
	t_l3bit	= t_volt & 0x3; 					/* 下位3ビット	*/
	
	t_upper	= (s2)S2_THERM_MODULE_TBL0[t_h7bit];
												/* 温度テーブル取得（ベース）	*/
	t_lower = (s2)S2_THERM_MODULE_TBL0[min(t_h7bit+1,127)];
												/* 温度テーブル取得（増分）		*/
	
	t_lcmp	= ((t_upper - t_lower) * t_l3bit) >> 3;
												/* 線形補間分演算	*/
	return(t_upper - t_lcmp);
}
