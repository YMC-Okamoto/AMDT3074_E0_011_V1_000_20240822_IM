f4			f4_vb_inv0_ref;										/* Unit=V:b相電圧指令値							*/

f4			f4_vu_inv0_svctrl;									/* Unit=V:U相電圧指令値							*/
f4			f4_vv_inv0_svctrl;									/* Unit=V:V相電圧指令値							*/
