/*===============================================================
+																+
+				Name:		void fi_1ms_int (void)				+
+			Function:		1msタイマ割込み関数					+
+																+
+					1)		1msタイマ割込みシーケンス制御		+
+					2)		1msタイマ割込みADデータ処理			+
+					3)		1msタイマ割込み速度制御				+
+					4)		1msタイマ割込みエラー検出			+
+					6)		CAN通信制御							+
+					7)		1msタイマI/F制御					+
+																+
+		Return Value:		No									+
+				date:		 10th Mar,2017						+
+																+
===============================================================*/
void fi_1ms_int (void)
{
	/*============================================================*/
	/*					   ローカル変数定義		　				  */
	/*============================================================*/
	u1		u1_temp_1;											/* テンポラリ変数(u1)							*/
	/*============================================================*/

	/*============================================================*/
	/*						多重割り込み許可					　*/
	/*============================================================*/
	__EI();
	/*============================================================*/
//	Set_TP2(1);
	/*============================================================*/
	/*							デバッグ演算					　*/
	/*============================================================*/
	u4_cnt_1ms++;
	/*============================================================*/

	/*============================================================*/
	/*					1msタイマ割込みシーケンス制御		　	  */
	/*============================================================*/
	fi_1ms_inv0_seqctrl();										/* 1msタイマ割込みシーケンス制御関数			*/
	/*============================================================*/

	/*============================================================*/
	/*				1msタイマ割込みdq軸電流指令値演算		　	  */
	/*============================================================*/
	fi_1ms_inv0_idqcom();										/* 1msタイマ割込みdq軸電流指令値演算関数		*/
	/*============================================================*/

	/*============================================================*/
	/*					1msタイマ割込みADデータ処理			　	  */
	/*============================================================*/
	fi_1ms_inv0_adctrl();										/* 1msタイマ割込みADデータ処理関数				*/
	/*============================================================*/

	/*============================================================*/
	/*					1msタイマ割込み速度制御				　	  */
	/*============================================================*/
	fi_1ms_inv0_wrctrl();										/* 1msタイマ割込み速度制御関数					*/
	/*============================================================*/

	/*============================================================*/
	/*					 1msタイマ割込みエラー検出				　*/
	/*============================================================*/
	if(0 == u1_flag_err_enable)
	{
		
		u2_cnt_err_enable++;
		if(u2_cnt_err_enable < 200)
		{
			Set_SDWN1(0);
			Set_SDWN2(0);
			Set_GB_CLR(0);
		}
		else if(u2_cnt_err_enable < 500)
		{
			Set_GB_CLR(1);
			Set_SDWN1(1);
			Set_SDWN2(1);
		}
		else
		{
			u1_flag_err_enable		= 1;
			u2_cnt_err_enable		= 0;
		}
		dpinv0_extgb_clr();
		dpinv1_extgb_clr();
	}
	else
	{
		// Set_GATE_EN0(1);
		fi_1ms_inv0_errctrl();									/* 1msタイマ割込みエラー検出関数				*/

	}
	/*============================================================*/

	/*============================================================*/
	/*						CAN通信制御							　*/
	/*============================================================*/
	if(0 == u1_flag_err_enable)
	{
		/* 運転できない状態ではCAN通信しない */
	}
	else
	{
		fb_can0_ctrl();
	}
	
	/*============================================================*/

	/*============================================================*/
	/*						タイマ割込みI/F制御				　    */
	/*============================================================*/
 	fi_1ms_inv0_ifctrl();										/* タイマ割込みI/F制御関数						*/
	/*=============================================================*/

	/*============================================================*/
	/*						Watcherデータ監視					　*/
	/*============================================================*/
	VECLIB_CMDMONI_1MS();
	/*============================================================*/
//	Set_TP2(0);
	/*============================================================*/
	/*							割込み禁止					　	  */
	/*============================================================*/
	__DI();
	/*============================================================*/

}

/*===============================================================
+																+
+				Name:		void fb_1ms_int_init (void)			+
+			Function:	1msタイマ割込み初期化関数				+
+																+
+				1)	1msタイマ割込みシーケンス制御初期化			+
+				2)	1msタイマ割込みdq軸電流指令値演算初期化		+
+				3)	1msタイマ割込みADデータ処理初期化			+
+				4)	1msタイマ割込み速度制御初期化				+
+				5)	1msタイマ割込みエラー検出初期化				+
+				6)	1msタイマ割込みキャプチャ処理初期化			+
+																+
+		Return Value:		No									+
+				date:		 10th Mar,2017						+
+																+
===============================================================*/
void fb_1ms_int_init(void)
{

	/*=============================================================*/
	/* 					エラー検出許可タイマ変数初期化	   		   */
	/*=============================================================*/
	u2_cnt_err_enable				= 0;
	u1_flag_err_enable				= 0;
	/*=============================================================*/

	/*=============================================================*/
	/* 					1msタイマ割込みシーケンス制御初期化  	   */
	/*=============================================================*/
	fb_1ms_inv0_seq_flaginit();									/* 1msタイマ割込みシーケンスフラグ初期化関数	*/
	fb_1ms_inv0_seq_modeinit();									/* 1msタイマ割込みシーケンスモード初期化関数	*/
	/*=============================================================*/

	/*=============================================================*/
	/* 				1msタイマ割込みdq軸電流指令値演算初期化  	   */
	/*=============================================================*/
	fb_1ms_inv0_idqcom_init();									/* 1msタイマ割込みdq軸電流指令値演算初期化関数	*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					1msタイマ割込みADデータ処理初期化  		   */
	/*=============================================================*/
	fb_1ms_inv0_adctrl_init();									/* 1msタイマ割込みADデータ処理初期化関数		*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					1msタイマ割込み速度制御初期化	  		   */
	/*=============================================================*/
	fb_1ms_inv0_wrctrl_init();									/* 1msタイマ割込み速度制御初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/*				　　1msタイマ割込みエラー検出初期化			　 */
	/*=============================================================*/
	fb_1ms_inv0_errctrl_init();									/* 1msタイマ割込みエラー検出初期化関数			*/
	/*=============================================================*/

    /*=============================================================*/
	/*				　　1msタイマ割込みI/F制御初期化    		　 */
	/*=============================================================*/
    fb_1ms_inv0_ifctrl_init();                                  /* 1msタイマ割込みI/F制御初期化関数              */
 	/*=============================================================*/

	/*============================================================*/
	/*					タイマ割込みFOリセット関数初期化	　	  */
	/*============================================================*/
//	fi_1ms_inv0_fo_reset(1);									/* 関数初期化									*/
	/*============================================================*/
}







