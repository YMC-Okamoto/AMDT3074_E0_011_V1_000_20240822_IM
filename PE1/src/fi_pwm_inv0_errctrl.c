/*							エラーフラグ定義				　 */
/*=============================================================*/
u4			u4_flag_inv0_error;									/* エラーフラグ									*/
u4			u4_flag_inv0_error1;								/* エラーフラグ									*/
u4			u4_flag_inv0_error2;								/* エラーフラグ									*/
/*=============================================================*/

/*=============================================================*/
/* 					エラー検出パラメータ変数定義  			   */
/*=============================================================*/
/* 保護レベル		*/
f4			f4_lev_oc_inv0_iac;									/* Unit=A:出力過電流レベル						*/
f4			f4_lev_ov_inv0_vdc;									/* Unit=V:直流過電圧レベル						*/

/* 保護時限			*/
u2			u2_cnt_oc_inv0_iac_pwm_max;							/* 出力過電流エラー時限							*/
u2			u2_cnt_ov_inv0_vdc_pwm_max;							/* 直流過電圧エラー時限							*/

u2			u2_cnt_oc_inv0_iu_pwm;								/* U相過電流エラータイマ						*/
u2			u2_cnt_oc_inv0_iv_pwm;								/* V相過電流エラータイマ						*/
u2			u2_cnt_oc_inv0_iw_pwm;								/* W相過電流エラータイマ						*/
u2			u2_cnt_ov_inv0_vdc_pwm;								/* 直流過電圧エラータイマ						*/
/*=============================================================*/

/*=============================================================*/
/* 					関数のプロトタイプ宣言					   */
/*=============================================================*/
void 	fi_pwm_inv0_errctrl			(void);						/* キャリア割込みエラー検出関数					*/
