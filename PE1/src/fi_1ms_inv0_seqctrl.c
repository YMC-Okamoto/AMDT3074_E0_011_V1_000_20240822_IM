u1 u1_fi_1ms_inv0_seq_stopctrl (void)
{
	switch(u1_seq_inv0_stopctrl)
	{
		/*============================================================*/
		/*						u1_SEQ_RUN_STOP_START	 			　*/
		/*============================================================*/
		case u1_SEQ_RUN_STOP_START:								/* シーケンス開始モード							*/

__DI();
		u1_flag_inv0_motctrl 		= 0;               			/* インバータ制御停止							*/
		u1_flag_inv0_offsetadjl		= 0;
__EI();
		u1_seq_inv0_stopctrl		= u1_SEQ_RUN_STOP_END;		/* シーケンス移行								*/

		break;
		/*============================================================*/

		/*============================================================*/
		/*						u1_SEQ_RUN_STOP_END 				　*/
		/*============================================================*/
		case u1_SEQ_RUN_STOP_END:								/* シーケンス終了モード							*/

		break;
		/*============================================================*/
	}

	/*============================================================*/
	/*						SEQ_RUN_STOP_CHECK					　*/
	/*============================================================*/
	if( u1_seq_inv0_stopctrl == u1_SEQ_RUN_STOP_END )			/* モードチェック								*/
	{															/* 終了モードで完了								*/
		u1_seq_inv0_stopctrl 		= u1_SEQ_RUN_STOP_START;	/* モードをスタートに戻す						*/
		return(1);
	}
	else
	{
		return(0);
	}
 	/*============================================================*/
}


/*===============================================================
+																+
+				Name:	u1 u1_fi_1ms_inv0_seq_errctrl (void)	+
+			Function:	1msタイマ割込み異常シーケンス関数		+
+																+
+		Return Value:		1:動作完了							+
+							0:動作中							+
+				date:		 10th Mar,2017						+
+																+
===============================================================*/
u1 u1_fi_1ms_inv0_seq_errctrl (void)
{
	switch(u1_seq_inv0_errctrl)
	{
		/*============================================================*/
		/*						SEQ_RUN_ERROR_START	 				　*/
		/*============================================================*/
		case u1_SEQ_RUN_ERROR_START:							/* シーケンス開始モード							*/

__DI();
		u1_flag_inv0_motctrl 		= 0;               			/* インバータ制御停止							*/
		u1_flag_inv0_offsetadjl		= 0;
__EI();

		u1_seq_inv0_errctrl			= u1_SEQ_RUN_ERROR_END;		/* シーケンス移行								*/

		break;
		/*============================================================*/

		/*============================================================*/
		/*						SEQ_RUN_ERROR_END	 				　*/
		/*============================================================*/
		case u1_SEQ_RUN_ERROR_END:								/* シーケンス終了モード							*/

		break;
		/*============================================================*/

	}

	/*============================================================*/
	/*						SEQ_RUN_ERROR_CHECK					　*/
	/*============================================================*/
	if( u1_seq_inv0_errctrl == u1_SEQ_RUN_ERROR_END )			/* モードチェック								*/
	{															/* 終了モードで完了								*/
		u1_seq_inv0_errctrl 		= u1_SEQ_RUN_ERROR_START;	/* モードをスタートに戻す						*/
		return(1);
	}
	else
	{
		return(0);
	}
	/*============================================================*/

}

