{
	/*=============================================================*/
	/* 						モード初期化				     	   */
	/*=============================================================*/
	u1_seq_inv0_runctrl				= u1_SEQ_STOP_RUN_START;	/* モードをスタートに戻す						*/
	u1_seq_inv0_stopctrl			= u1_SEQ_RUN_STOP_START;
	u1_seq_inv0_errctrl	 			= u1_SEQ_RUN_ERROR_START;
	/*=============================================================*/

}


