/*=============================================================*/

/*=============================================================*/
/* 					インバータPWM出力状態フラグ			 	   */
/*=============================================================*/
u1			u1_pwm_inv0_status;									/* インバータPWM出力状態フラグ					*/
																/* 0:停止中, 1:出力中							*/
/*=============================================================*/

/*=============================================================*/
/* 						PWM/サンプリング周波数設定値		   */
/*=============================================================*/
u1			u1_flag_pwm_inv0_source;							/* PWM割込み位置設定							*/
																/* 0:禁止　1:000(山)　2:111(谷)　3：両方		*/

u4			u4_fc_inv0_lsb_0;									/* Unit=Hz:PWM周波数設定値						*/

f4			f4_fs_inv0_ctrl;									/* Unit=Hz:サンプリング周波数(fc*2)				*/
f4			f4_ts_inv0_ctrl;									/* Unit=sec:サンプリング周期					*/
/*=============================================================*/

/*=============================================================*/
/* 						デバッグ用変数定義			   		   */
/*=============================================================*/
u4			u4_cnt_pwm;
/*=============================================================*/

/*=============================================================*/
/* 					関数のプロトタイプ宣言					   */
/*=============================================================*/
void 		fi_pwm_int			(void);							/* キャリア割込み関数							*/
void 		fb_pwm_int_init		(void);							/* キャリア割込み処理初期化関数					*/
/*=============================================================*/

/*===============================================================
+																+
+				Name:		void fi_pwm_int (void)				+
+			Function:		キャリア割込み関数					+
+																+
+					1)	キャリア割込みWatcherデータ監視			+
+					2)	キャリア割込みパラメータ測定			+
+					3)	キャリア割込みエラー検出				+
+					4)	サンプリング周波数設定					+
+					5)	PWM出力許可設定							+
+					6)	キャリア割込みエンコーダ処理			+
+					7)	キャリア割込み電圧制御誤差補償			+
+					8)	キャリア割込みADデータ処理				+
+					9)	キャリア割込みdq軸電流制御				+
+					10)	キャリア割込みSPWM電圧制御制御			+
+					11)	キャリア割込み1パルス制御				+
+																+
+		Return Value:		No									+
+				date:		 10th Mar,2017						+
+																+
===============================================================*/
void fi_pwm_int (void)
{

	/*============================================================*/
	/*			ADC0割込みフラグクリア(ForAD変換ウェイト)		  */
	/*============================================================*/
	Set_ADC0_SG4_IRF(0);										/* ADCC0 SG4 割り込みフラグクリア */
	/*============================================================*/
	
	/*============================================================*/
	/*						多重割り込み許可					　*/
	/*============================================================*/
	__EI();
	/*============================================================*/
	
	/*============================================================*/
	/*							デバッグ演算					　*/
	/*============================================================*/
	u4_cnt_pwm++;
	/*============================================================*/

	/*============================================================*/
	/* 				　	キャリア割込みエンコーダ処理			  */
	/*============================================================*/
	{
	fi_pwm_inv0_encctrl();										/* キャリア割込みエンコーダ処理関数				*/
	}
	/*============================================================*/
	
	/*============================================================*/
	/* 			 	 キャリア割込み同期PWM制御			 		　*/
	/*============================================================*/
	fi_pwm_inv0_syncctrl();										/* キャリア割込み同期PWM制御関数				*/
	/*============================================================*/
	
	/*============================================================*/
	/* 					　	サンプリング周波数設定				  */
	/*============================================================*/
	if(3 == u1_flag_pwm_inv0_source)
	{
		// 山谷割込み
		f4_fs_inv0_ctrl					= ((f4)(u4_fc_inv0_lsb_0)) * ((f4)(2.0));
																/* サンプリング周期(=PWM×2)					*/
	}
	else
	{
		// 山または谷割込み
		f4_fs_inv0_ctrl					= ((f4)(u4_fc_inv0_lsb_0)) / (f4)(N_FC_INV0+1);
																/* サンプリング周期(=PWM×1)					*/
	}

	if(f4_fs_inv0_ctrl > ((f4)(0.0)))	{f4_ts_inv0_ctrl	= ((f4)(1.0)) / f4_fs_inv0_ctrl;}
	else{}														/* サンプリング周期								*/
	/*============================================================*/

	/*============================================================*/
	/* 			 	 キャリア割込みパラメータ測定		 		　*/
	/*============================================================*/
	fi_pwm_inv0_invadj();										/* キャリア割込パラメータ測定関数				*/
	/*============================================================*/

	/*============================================================*/
	/*						PWM出力許可設定				　	  	  */
	/*============================================================*/
	if(0 == u4_flag_inv0_error)									/* 異常が発生していない							*/
	{
		if(0 == u1_pwm_inv0_status)								/* PWM停止状態									*/
		{
			if(1 == u1_flag_inv0_motctrl)						/* モータ制御許可								*/
			{
__DI();
				dpinv0_extgb_clr();
				dpinv0_start();									/* PWM出力許可									*/
				u1_pwm_inv0_status	= 1;						/* PWM出力状態フラグセット						*/
__EI();
			}
			else{}
		}
		else													/* PWM出力状態									*/
		{
			if(0 == u1_flag_inv0_motctrl)						/* モータ制御禁止								*/
			{
__DI();
				dpinv0_stop();									/* PWM出力禁止									*/

				u1_pwm_inv0_status	= 0;						/* PWM出力状態フラグクリア						*/
__EI();
			}
			else{}
		}
	}
	else														/* 異常発生時									*/
	{
__DI();
		dpinv0_stop();											/* PWM出力禁止									*/

		u1_pwm_inv0_status			= 0;						/* PWM出力中フラグ								*/
__EI();
	}
	/*============================================================*/

	/*============================================================*/
	/*					キャリア割込みADデータ処理			　	  */
	/*============================================================*/
	fi_pwm_inv0_adctrl();										/* キャリア割込みADデータ処理関数				*/
	/*============================================================*/

	/*============================================================*/
	/* 					キャリア割込みエラー検出				  */
	/*============================================================*/
	if(1 == u1_flag_err_enable)
	{
		fi_pwm_inv0_errctrl();									/* キャリア割込みエラー検出関数					*/
	}
	else{}
	/*============================================================*/

	/*============================================================*/
	/* 					キャリア割込みdq軸電流制御				  */
	/*============================================================*/
	fi_pwm_inv0_idqctrl();										/* キャリア割込みdq軸電流制御関数				*/
	/*============================================================*/
	
	/*============================================================*/
	/* 					キャリア割込み電圧制御誤差補償			  */
	/*============================================================*/
	fi_pwm_inv0_vctrlerr();										/* キャリア割込み電圧制御誤差補償関数			*/
	/*============================================================*/

	/*============================================================*/
	/* 				   キャリア割込み電圧指令値設定				  */
	/*============================================================*/

	if(0 == u1_flag_inv0_modevctrl)
	{
		fi_pwm_inv0_svctrl();									/* キャリア割込みSPWM電圧制御関数				*/
	}
	else
	{
		fi_pwm_inv0_1pulse();									/* キャリア割込み1パルス制御関数				*/
	}

	/*============================================================*/

	/*============================================================*/
	/*				キャリア割込みWatcherデータ監視				　*/
	/*============================================================*/
	VECLIB_CMDMONI_PWM();
	/*============================================================*/
	
	;/*============================================================*/
	/*							割込み禁止					　	  */
	/*============================================================*/
	__DI();
	/*============================================================*/

}

/*===============================================================
+																+
+				Name:		void fb_pwm_int_init (void)			+
+			Function:		キャリア割込み初期化関数			+
+																+
+			1)		PWM/サンプリング周波数初期化				+
+			2)		キャリア割込みdq軸電流制御初期化			+
+			3)		キャリア割込みSPWM電圧制御初期化			+
+			4)		キャリア割込み1パルス制御初期化				+
+			5)		キャリア割込みエンコーダ処理初期化			+
+			6)		キャリア割込み電圧制御誤差補償初期化		+
+			7)		キャリア割込みADデータ処理初期化			+
+			8)		キャリア割込みエラー検出初期化				+
+			9)		キャリア割込みパラメータ測定初期化			+
+																+
+		Return Value:		No									+
+				date:		 10th Mar,2017						+
+																+
===============================================================*/
void fb_pwm_int_init (void)
{

	/*=============================================================*/
	/* 				インバータPWM出力状態フラグ初期化			   */
	/*=============================================================*/
	u1_pwm_inv0_status				= 0;
	/*=============================================================*/
	
	/*=============================================================*/
	/* 					キャリア割込み同期PWM制御初期化			   */
	/*=============================================================*/
	fb_pwm_inv0_syncctrl_init();								/* キャリア割込み同期PWM制御初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					　PWM/サンプリング周波数初期化			   */
	/*=============================================================*/
	u1_flag_pwm_inv0_source				= ((u1)(PWM_SOURCE_INV0));

	u4_fc_inv0_lsb_0				= ((u4)(FC_PWM_INV0));

	if(3 == u1_flag_pwm_inv0_source)
	{
		// 山谷割込み
		f4_fs_inv0_ctrl				= ((f4)(u4_fc_inv0_lsb_0)) * ((f4)(2.0));
																/* サンプリング周期(=PWM×2)					*/
	}
	else
	{
		// 山または谷割込み
		f4_fs_inv0_ctrl				= ((f4)(u4_fc_inv0_lsb_0)) / (f4)(N_FC_INV0+1);
	}

	f4_ts_inv0_ctrl					= ((f4)(1.0)) / f4_fs_inv0_ctrl;
	/*=============================================================*/

	/*=============================================================*/
	/* 					キャリア割込みdq軸電流制御初期化		   */
	/*=============================================================*/
	fb_pwm_inv0_idqctrl_init();									/* キャリア割込みdq軸電流制御初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					キャリア割込みSPWM電圧制御初期化		   */
	/*=============================================================*/
	fb_pwm_inv0_svctrl_init();									/* キャリア割込みSPWM電圧制御初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					キャリア割込み1パルス制御初期化			   */
	/*=============================================================*/
	fb_pwm_inv0_1pulse_init();									/* キャリア割込み1パルス制御初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/* 				キャリア割込みエンコーダ処理初期化			   */
	/*=============================================================*/
	fb_pwm_inv0_encctrl_init();									/* キャリア割込みエンコーダ処理初期化関数		*/
	/*=============================================================*/

	/*=============================================================*/
	/* 				キャリア割込み電圧制御誤差補償初期化		   */
	/*=============================================================*/
	fb_pwm_inv0_vctrlerr_init();								/* キャリア割込み電圧制御誤差補償初期化関数		*/
	fb_pwm_vctrlerr_init();										/* キャリア割込み電圧制御誤差テーブル初期化関数	*/
	/*=============================================================*/

	/*=============================================================*/
	/* 				キャリア割込みADデータ処理初期化			   */
	/*=============================================================*/
	 fb_pwm_inv0_adctrl_init();									/* キャリア割込みADデータ処理初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					キャリア割込みエラー検出初期化			   */
	/*=============================================================*/
	fb_pwm_inv0_errctrl_init();									/* キャリア割込みエラー検出初期化関数			*/
	/*=============================================================*/

	/*=============================================================*/
	/* 					キャリア割込みパラメータ測定初期化		   */
	/*=============================================================*/
	fb_pwm_inv0_invadj_init();									/* キャリア割込みパラメータ測定初期化関数		*/
	/*=============================================================*/

}


