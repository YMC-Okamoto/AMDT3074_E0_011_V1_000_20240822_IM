/*						デバッグ用変数定義					   */
/*=============================================================*/
f4		f4_x_2_nom_1d;
f4		f4_z_2_nom_1d;
s4		s4_x_2_id_1d, s4_z_2_id_1d;
s4		s4_x_2_id_p1_1d, s4_z_2_id_p1_1d;
f4		f4_kw_x_2_1d, f4_kw_z_2_1d;



f4	C00_2_1d, C01_2_1d, C10_2_1d, C11_2_1d;
/*					d軸電流指令, &Lm		 											*/
u1 u1_lm_map_1d_get(f4 f4_x_2_1d, f4 *f4_a_2_1d)
{
	/*============================================================*/
	/*					   ローカル変数定義		　				  */
	/*============================================================*/
	float	f4_temp0;
	s4		s4_temp0;

	u1		u1_error = 0;
	/*============================================================*/

	/*============================================================*/
	/*					   引数の正規化			　				  */
	/*============================================================*/
	/* X 処理　*/
	f4_x_2_nom_1d		= (((f4)(f4_x_2_1d)) - ((f4)(ORIGIN_X_2_1D))) / ((f4)(RESO_X_2_1D));
	f4_kw_x_2_1d		= modff(f4_x_2_nom_1d, &f4_temp0);
	s4_x_2_id_1d		= (s4)f4_temp0;
	
	/* エラー検出			*/
	u1_error	|= (s4_x_2_id_1d<0)?(1):((s4_x_2_id_1d>=N_X_2_1D)?(1):(0));
	if(s4_x_2_id_1d<0)
	{
		s4_x_2_id_1d		= 0;
		f4_kw_x_2_1d		= 0.0;
		u1_error	|= 0x1;
	}
	else if(s4_x_2_id_1d<N_X_2_1D)
	{
	}
	else
	{
		s4_x_2_id_1d		= N_X_2_1D - 1;
		f4_kw_x_2_1d		= 1.0;
		u1_error	|= 0x1;
	}

	if(f4_kw_x_2_1d < (f4)(0.))
	{
		f4_kw_x_2_1d			= (f4)(0.);
	}
	else{}
	/*============================================================*/

	/*============================================================*/
	/*					  データ取得			　				  */
	/*============================================================*/
	s4_x_2_id_p1_1d	= s4_x_2_id_1d+1;
	s4_x_2_id_p1_1d	= (s4_x_2_id_p1_1d<N_X_2_1D)?(s4_x_2_id_p1_1d):(N_X_2_1D-1);

	// trq_limit_n
	C00_2_1d		= (f4)map_lm_1d[0][s4_x_2_id_1d];
	C10_2_1d		= (f4)map_lm_1d[0][s4_x_2_id_p1_1d];
	*f4_a_2_1d		= (1.0-f4_kw_x_2_1d)*C00_2_1d
					+ (f4_kw_x_2_1d)*C10_2_1d;
	/*============================================================*/

	/*============================================================*/
	/*					  戻り値				　				  */
	/*============================================================*/
	return(u1_error);
	/*============================================================*/
}
