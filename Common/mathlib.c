/* Tan-1関数ライブラリ 		*/
/* rad = dpatan(y, x);		*/
/*     = Tan-1(y/x)			*/
/* rad:-16384(-π) ~ +163863(+π)	*/
/* x,y:-2^15 ~ +2^15-1	*/
int	dpatan(int s32_y, int s32_x)
{
	int 			s32_theta;
	unsigned int 	_temp_indx;
	int				s32_y_x;
	unsigned int	u32_y_x;
	unsigned int	u32_cmp;

	s32_theta = 0;
	
	if(s32_x == 0)
	{
		if(s32_y >= 0)
		{
			s32_y_x = 32767;
		}
		else
		{
			s32_y_x = -32768;
		}
	}
	else
	{
		s32_y_x = (s32_y << 16) / s32_x;		/* y/xを計算		*/
		s32_y_x = s32_y_x >> 7;
	}
	
	if(s32_y_x < 0)								/* 符号無しに直す		*/
	{
		u32_y_x = -s32_y_x;
	}
	else
	{
		u32_y_x = s32_y_x;
	}

	/* データ領域の振り分け								*/
	if(u32_y_x >= 24576)
	{
		s32_theta	= 8191;
	}
	else
	{
		if(u32_y_x <= 512)
		{
			_temp_indx 	= u32_y_x >> 3;				/* index取得。index=3bitシフト(引数増分8)			*/
			u32_cmp 	= u32_y_x & 0x07;			/* 線形補完用下位3bit取得(引数増分8)				*/
		}
		else if(u32_y_x <= 1024)
		{
			_temp_indx 	= ((u32_y_x - 512) >> 4) + 63;	/* index取得。下位9bit取り出して4bit右シフト(引数増分16)+63したのがindex	*/
			u32_cmp 	= u32_y_x & 0x0f;				/* 線形補完用下位4bit取得(引数増分16)				*/
		}
		else if(u32_y_x <= 2048)
		{
			_temp_indx 	= ((u32_y_x - 1024) >> 6) + 96;	/* index取得。下位10bit取り出して6bit右シフト(引数増分64)+96したのがindex	*/
			u32_cmp 	= u32_y_x & 0x3f;				/* 線形補完用下位6bit取得(引数増分64)				*/
		}
		else if(u32_y_x <= 4096)
		{
			_temp_indx 	= ((u32_y_x - 2048) >> 8) + 112;	/* index取得。下位11bit取り出して8bit右シフト(引数増分256)+112したのがindex	*/
			u32_cmp 	= u32_y_x & 0xff;				/* 線形補完用下位8bit取得(引数増分256)				*/
		}
		else if(u32_y_x <= 8192)
		{
			_temp_indx 	= ((u32_y_x - 4096) >> 10) + 120;	/* index取得。下位12bit取り出して10bit右シフト(引数増分1024)+120したのがindex	*/
			u32_cmp 	= u32_y_x & 0x3ff;				/* 線形補完用下位10bit取得(引数増分1024)				*/
		}
		else if(u32_y_x < 24576)
		{
			_temp_indx 	= ((u32_y_x - 8192) >> 12) + 124;	/* index取得。下位13bit取り出して12bit右シフト(引数増分4096)+124したのがindex	*/
			u32_cmp 	= u32_y_x & 0xfff;				/* 線形補完用下位12bit取得(引数増分4096)				*/
		}

		s32_theta	= (int)u16_dpatan_tbl2[_temp_indx][0] + (int)((u16_dpatan_tbl2[_temp_indx][1] * u32_cmp) >> 11);
		s32_theta	= s32_theta >> 1;
	}

	if(s32_y >= 0)
	{
		if(s32_x >= 0)
		{
			return(s32_theta);
		}
		else
		{
			return(16383 - s32_theta);
		}					
	}
	else
	{
		if(s32_x >= 0)
		{
			return(-s32_theta);
		}
		else
		{
			return(-16384 + s32_theta);
		}					
	}	

	return(0);
}

