/* SQRT関数ライブラリ 		*/
/* sqrt = dpsqrt2(x);		*/
/*      = x^(0.5)			*/
/* sqrt:-2^31 ~ +2^31-1		*/
/* x:-2^31 ~ +2^31-1		*/
int testrt0, testrt1, testrt2, testrt3;
int	dpsqrt(int s32_x)
{
	int 			s32_sqrt;
	unsigned int 	u32_x;
	unsigned int 	u32_x_nom;
	unsigned int 	u32_x_cmpbuf[16];
	unsigned int 	u32_order;
	unsigned int 	_temp_indx;
	unsigned int 	u32_sqrt0;
	unsigned int 	u32_sqrt1;
	unsigned int 	u32_sqrt2;
	unsigned int 	u32_sqrt_cmp0;
	unsigned int 	u32_sqrt_cmp1;
	unsigned int 	u32_sqrt_cmp2;

	/* 負は0を返す */
	if(s32_x < 0)
	{
		u32_x = 0;
	}
	else
	{
		u32_x = s32_x;
	}

	/* 0~255に正規化する */
	u32_order = 0;				/* 2ビットシフト(=2^2)した回数をカウント */
	u32_x_nom = u32_x;
	u32_x_cmpbuf[0] = u32_x;
	while(u32_x_nom > 255)
	{
		u32_x_nom = u32_x_nom >> 2;
		u32_order++;
		u32_x_cmpbuf[u32_order] = u32_x_nom;
	}

	_temp_indx = u32_x_nom;
	
	u32_sqrt0		= (int)u16_dpsqrt_tbl2[_temp_indx][0];
	u32_sqrt_cmp0	= (int)u16_dpsqrt_tbl2[_temp_indx][1];
	
	u32_sqrt1	= u32_sqrt0 << u32_order;
	
	if(u32_order > 4)
	{
		u32_sqrt_cmp1 = (u32_x_cmpbuf[u32_order - 4]) - (u32_x_nom << 8);
		
		testrt3 = 5555;
	}
	else
	{
		u32_sqrt_cmp1 = u32_x_cmpbuf[0] - (u32_x_nom << (u32_order * 2));
		testrt0 = u32_x_cmpbuf[0];
		testrt1 = u32_x_nom;
		testrt2 = u32_x_nom << (u32_order * 2);		
	}

	u32_sqrt_cmp2 = (u32_sqrt_cmp0 * u32_sqrt_cmp1) >> (16 - u32_order);
	
	u32_sqrt2 = (u32_sqrt1 + u32_sqrt_cmp2) >> 12;
	
	s32_sqrt = u32_sqrt2;

	return(s32_sqrt);
}


