/* cos関数ライブラリ 	*/
/* a = dpcos(rad);		*/
/* a:-32768 ~ +32767	*/
/* rad:-65536(-2π) ~ +65535(+2π)	*/

#pragma inline dpcos
int	dpcos(int s32_rad)
{
	int	s32_16bit_rad;
	unsigned int u32_16bit_rad;
	unsigned int u32_14bit_rad;
	unsigned int u32_2bit_rad_dom;
	unsigned int u32_9bit_rad_tbl;
	unsigned int u32_4bit_rad_tbl;
	int s32_cos;
	
	unsigned int _temp_indx;


	s32_16bit_rad = s32_rad + 0x8000;					/* 符号無し16bitに直す(0x0:0 0xffff:4π)		*/
	u32_16bit_rad = s32_16bit_rad & 0x7fff;				/* 上位ビットの掃除(0x0:0 0x7fff:2π)			*/
	u32_14bit_rad = u32_16bit_rad & 0x1fff;				/* 下位14bit(1/2π)取得(0x1fff:1/2π)		*/
	u32_9bit_rad_tbl = u32_14bit_rad >> 4;				/* テーブル参照用下位9bit取得(0x1ff:1/2π)		*/
	u32_4bit_rad_tbl = u32_14bit_rad & 0xf;				/* 線形補完用下位4bit取得		*/
	u32_2bit_rad_dom = u32_16bit_rad >> 13;				/* 領域判定用に14,15bit目取得					*/

	switch(u32_2bit_rad_dom)							/* 領域の振り分け								*/
	{
		case 3:		/* 3/4π～π	*/
		_temp_indx = u32_9bit_rad_tbl;
		s32_cos	= ( int)u16_dpsin_tbl2[_temp_indx][0] + ( int)((u16_dpsin_tbl2[_temp_indx][1] * u32_4bit_rad_tbl) >> 12);
		break;
		
		case 0:		/* 0～1/2π		*/
		_temp_indx = 0x200 - u32_9bit_rad_tbl;
		s32_cos	= ( int)u16_dpsin_tbl2[_temp_indx][0] - ( int)((u16_dpsin_tbl2[_temp_indx][1] * u32_4bit_rad_tbl) >> 12);
		break;

		case 1:		/* 1/2π～π	*/
		_temp_indx = u32_9bit_rad_tbl;
		s32_cos	= - (( int)u16_dpsin_tbl2[_temp_indx][0] + ( int)((u16_dpsin_tbl2[_temp_indx][1] * u32_4bit_rad_tbl) >> 12));
		break;
		
		case 2:		/* π～3/4π	*/
		_temp_indx = 0x200 - u32_9bit_rad_tbl;
		s32_cos	= - (( int)u16_dpsin_tbl2[_temp_indx][0] - ( int)((u16_dpsin_tbl2[_temp_indx][1] * u32_4bit_rad_tbl) >> 12));
		break;
		
		default:
		break;
	}
	
	return(s32_cos>>1);
}

