float dpatan2_f(float y, float x)
{
    float f4_wt;
    
    if (y < 0)
    {
        if (x < 0)
        {
            if (-y < -x)
            { 
                f4_wt = -PI + Table_atan2Lookup(-y / -x);
            }
            else
            { 
                f4_wt = -(PI*0.5) - Table_atan2Lookup(-x / -y);
            }
        }
        else 
        {
            if (-y < x)
            { 
                f4_wt = -Table_atan2Lookup(-y / x); 
            }
            else
            { 
                f4_wt = -(PI*0.5) + Table_atan2Lookup(x / -y);
            }
        }
    }
    else // y >= 0
    {
        if (x < 0)
        {
            if (y < -x)
            { 
                f4_wt = PI - Table_atan2Lookup(y / -x);
            }
            else
            { 
                f4_wt = (PI*0.5) + Table_atan2Lookup(-x / y);
            }
        }
        else 
        {
            if (y < x)
            {
                f4_wt = Table_atan2Lookup(y / x);
            }
            else
            { 
                f4_wt = (PI*0.5) - Table_atan2Lookup(x / y); 
            }
        }
    }
    return (f4_wt);
}
