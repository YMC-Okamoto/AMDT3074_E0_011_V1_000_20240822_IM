/*==============================================================*/
/*	TAUD1用クロック初期化関数									*/
/*	引数：														*/
/*			なし												*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*			制御タイマ：TAUD1									*/
/*			CK0	= PCLK											*/
/*			CK1 = PCLK/2										*/
/*			CK2 = PCLK/8										*/
/*			CK3_PRE = PCLK										*/
/*			CK3	= 1MHzになるように設定							*/
/*			TAUD1が停止中に実行の事								*/
/*--------------------------------------------------------------*/
void	taud1prescale_0_2_8_0_init(void)
{
	/*-------------------------------------------------*/
	/* Set Clock Frequency                             */
	/*-------------------------------------------------*/
//	TAUD1.TPS = 0b0000 00010 0001 0000;				/* Prescaler Clock Select */
	TAUD1.TPS.UINT16 = 0x0310;

/*							CK3_PRE[15-12] = PCLK/2^0
							CK2[11- 8]     = PCLK/2^3
							CK1[ 7- 4]     = PCLK/2^1
							CK0[ 3- 0]     = PCLK/2^0
*/
	/*-------------------------------------------------*/
	/* Set Baudrate  CK3 = CK3PRE/BRS                  */
	/*-------------------------------------------------*/
	TAUD1.BRS			= (u4)(__CLKC_HSB)-1;		/* CK3_PRE/(TAUD1BRS+1)=1MHz */
	
}

