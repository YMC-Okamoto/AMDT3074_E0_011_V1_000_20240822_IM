/*==============================================================*/
/*	インターバルタイマ10初期化関数								*/
/*	引数：														*/
/*			u4	u4_interval_us	: インターバル時間[uS]			*/
/*			u1	u1_intlv		:割り込みレベル					*/
/*			u1 u1_intcpu	: 2: PE2 /2以外:PE1					*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUD0_CH0				*/
/*							プリスケーラクロック CK3を選択		*/
/*	注意！！　CK3の分解能は、1uSになっている事					*/
/*--------------------------------------------------------------*/

/*=============================================================*/
/*	TAUD1初期化関数（タイマ割り込み）						   */
/*=============================================================*/
void interval10_init ( u4 u4_interval_us, u1 u1_intlv , u1 u1_intcpu)
{
	/*-------------------------------------------------*/
	/* 　TAUD1 CH0停止 			                      */
	/*-------------------------------------------------*/
	TAUD1.TT.UINT16 		= 1;						/* CH0 STOP					*/

	/*-------------------------------------------------*/
	/* Channel Data Register      	            	   */
	/*-------------------------------------------------*/
	TAUD1.CDR0 = u4_interval_us - 1;

	/*-------------------------------------------------*/
	/*  Channel Counter Register 			   */
	/*-------------------------------------------------*/
	TAUD1.CNT0 = u4_interval_us - 1;

	/*-------------------------------------------------*/
	/* Channel ModeOS Register	                  		*/
	/*-------------------------------------------------*/
//	TAUD1.CMOR0.BIT.CKS	= 3;						/* 動作クロック（CK3）		*/
//	TAUD1.CMOR0.BIT.CCS	= 0;						/* カウントクロック(CKSによる）	*/	
//	TAUD1.CMOR0.BIT.MAS	= 0;						/* スレーブ					*/			
//	TAUD1.CMOR0.BIT.STS	= 0;						/* ソフトウェアトリガ		*/
//	TAUD1.CMOR0.BIT.COS	= 0;						/*							*/	
//	TAUD1.CMOR0.BIT.MD 	= 0;						/* インターバルタイマモード	*/

	TAUD1.CMOR0.UINT16		= 0xC000 ;

	/*-------------------------------------------------*/
	/* Channel Mode User Register                      */
	/*-------------------------------------------------*/
	TAUD1.CMUR0.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */
	
	/*-------------------------------------------------*/
	/* Channel Status Clear Register                   */
	/*-------------------------------------------------*/
	TAUD1.CSC0.UINT8 		= 1;							/* OVFフラグクリア 				*/

	/*============== TAUD1 各チャネル一括	=================*/

	/*-------------------------------------------------*/
	/* Channel Output Enable Register                  */
	/*-------------------------------------------------*/
	TAUD1.TOE.UINT16		&= ~0x1;						/* 出力禁止						 */

	/*-------------------------------------------------*/
	/* Channel Output Mode Register                    */
	/*-------------------------------------------------*/
	TAUD1.TOM.UINT16 		&= ~0x1;						/* チャネル単体動作				 */

	/*-------------------------------------------------*/
	/* Channel Output Configuration Register           */
	/*-------------------------------------------------*/
	TAUD1.TOC.UINT16		&= ~0x1;						/* トグルモード					 */

	/*-------------------------------------------------*/
	/* Channel  Output Level Register   		       */
	/*-------------------------------------------------*/
	TAUD1.TOL.UINT16		&= ~0x1;						/* アクティブレベルHI			 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD1.TDE.UINT16 		&= ~0x1;						/* デットタイム動作禁止			 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Mode                    */
	/*-------------------------------------------------*/
	TAUD1.TDM.UINT16	 	&= ~0x1;						/* 偶数チャネル					 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Level                   */
	/*-------------------------------------------------*/
	TAUD1.TDL.UINT16		&= ~0x1;						/* 正相にデットタイム付加		 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD1.TRE.UINT16		&= ~0x1;						/* リアルタイム出力禁止			 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Register                */
	/*-------------------------------------------------*/
	TAUD1.TRO.UINT16 		&= ~0x1;						/* TRO出力 LOW					*/

	/*-------------------------------------------------*/
	/* Channel RealTime Output Control Register        */
	/*-------------------------------------------------*/
	TAUD1.TRC.UINT16 		&= ~0x1;						/* リアルタイム出力生成トリガ選択 */

	/*-------------------------------------------------*/
	/* Channel modulation output enable Register       */
	/*-------------------------------------------------*/
	TAUD1.TME.UINT16		&= ~0x0001;						/* 変調禁止							*/
	/*====================================================*/

	/* 割り込みレベル設定	*/
	if ( 2 == u1_intcpu )
	{
		INTC2.EIBD98.BIT.GPID	= 1;							/* CPU2にバインド					*/
		INTC2.EIBD98.BIT.PEID	= 2;							/* CPU2にバインド					*/
	}
	else
	{
		INTC2.EIBD98.BIT.GPID	= 0;							/* CPU1にバインド					*/
		INTC2.EIBD98.BIT.PEID	= 1;							/* CPU1にバインド					*/
	}
	if( u1_intlv < 16 )
	{
		INTC2.EIC98.BIT.EIRF98	= 0 ;						/* 割り込みフラグクリア				*/
		INTC2.EIC98.BIT.EIP98	= u1_intlv ;				/* 割り込みレベル設定				*/
		INTC2.EIC98.BIT.EITB98	= 1;						/* テーブル参照方式					*/
//		INTC2.EIC98.BIT.EITB98	= 0;						/* 直接分岐方式						*/
		INTC2.EIC98.BIT.EIMK98	= 0 ;						/* 割り込みマスククリア				*/
	}
	else
	{
		INTC2.EIC98.BIT.EIMK98	= 1 ;						/* 割り込みマスク					*/
	}

}

