/*==============================================================*/
/*	TAUD1 CH15キャプチャ値取得関数								*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　	カウンタ値を返す									*/
/*																*/
/*==============================================================*/
u2 phase_capture1_15_cnt_read(void)
{
	u2 	u2_cnt	;
	
	if ( 0 == TAUD1.CSR15.BIT.OVF )				/* オーバーフローなし	*/
	{
		u2_cnt = TAUD1.CDR15 ;
	}
	else
	{
//		u2_cnt 						= 0xFFFF;
		u2_cnt 						= TAUD1.CDR15 ; /* 位相キャプチャなので、そのまま値を返す*/
		TAUD1.CSC15.UINT8 			= 1;		/* OverflowFlagクリア	*/		
	}

	return((u2)u2_cnt);
}

/*==============================================================*/
/*	TAUD1 CH15キャプチャフラグ取得関数							*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　	キャプヤが行われたか？どうかを返す					*/
/*			本関数で、割り込みフラグをクリアする				*/
/*			非同期入力の為、入力周波数に対して、				*/
/*			十分、読み出し間隔を早くする必要がある				*/
/*																*/
/*==============================================================*/
u1 phase_capture1_15_flag_read(void)
{
	u1 	u1_flag	;
	
	u1_flag = 0;
	
	if ( 1 == INTC2.EIC113.BIT.EIRF113 )
	{
		u1_flag 	= 1;
		INTC2.EIC113.BIT.EIRF113 	= 0;				/* 割り込みフラグクリア	*/
	}
	else
	{
		u1_flag 	= 0;
	}

	return(u1_flag);
}

