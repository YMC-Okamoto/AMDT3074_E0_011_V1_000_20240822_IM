/*==============================================================*/
/*　PWMタイマタイマ1_15変調率設定関数							*/
/*	引数：	f4		f4_m :PWM変調率　　0~1.0					*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUD1_CH14/15			*/
/*--------------------------------------------------------------*/	
void pwm1_15_setm_f ( f4 f4_m )
{

	u2	u2_cnt_m;
	
	if ( f4_m >= 1.0 )
	{
		u2_cnt_m = (u2)(TAUD1.CDR14+1) ;
	}
	else
	{
		if ( f4_m <= 0 )
		{
			u2_cnt_m = (u2)(0);
		}
		else
		{
			u2_cnt_m = (u2)(f4_m * (f4)(TAUD1.CDR14));
		}
	}

	TAUD1.CDR15	= (u2)u2_cnt_m;	
	TAUD1.RDT.UINT16  = 0xC000 ;		/* CH14/15 リロード許可		*/

}

