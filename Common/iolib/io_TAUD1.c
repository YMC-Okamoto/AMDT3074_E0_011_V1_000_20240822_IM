/*==============================================================*/
/*	PWM1_15タイマ初期化関数										*/
/*	引数：														*/
/*			u4 u4_freq			:キャリア周波数[Hz]				*/
/*			u1 u1_logic			:PWM論理	0:正論理　それ以外:負論理	*/
/*			u1	u1_intlv		:割り込みレベル					*/
/*			u1 u1_intcpu	: 2: PE2 /2以外:PE1					*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUD1_CH14/15			*/
/*							P3_4/TAUD1O15						*/
/*							プリスケーラクロック CK0を選択		*/
/*	注意！！　CK0の分解能は、12.5nSになっている事				*/
/*--------------------------------------------------------------*/
void pwm1_15_init (  u4 u4_freq, u1 u1_logic ,u1 u1_intlv  , u1 u1_intcpu )
{
	/*-------------------------------------------------*/
	/* 　P1_15入力モード   			                   */
	/*-------------------------------------------------*/
	PORT.PCR1_15.UINT32		=	0x00000010;				/* 入力		*/
	
	/*-------------------------------------------------*/
	/* 　TAUD1 CH14,15停止 			                      */
	/*-------------------------------------------------*/
	TAUD1.TT.UINT16 		= 0xC000;					/* CH14,15 STOP					*/

	
	/*-------------------------------------------------*/
	/* Channel ModeOS Register	                  		*/
	/*-------------------------------------------------*/	
	/* マスタ（周期制御	）								*/
//	TAUD1.CMOR14.BIT.CKS	= 0;						/* 動作クロック（CK3）		*/
//	TAUD1.CMOR14.BIT.CCS	= 0;						/* カウントクロック(CKSによる）	*/	
//	TAUD1.CMOR14.BIT.MAS	= 1;						/* マスタ					*/			
//	TAUD1.CMOR14.BIT.STS	= 0;						/* ソフトウェアトリガ		*/
//	TAUD1.CMOR14.BIT.COS	= 0;						/*							*/	
//	TAUD1.CMOR14.BIT.MD 	= 0;						/* インターバルタイマモード	*/
//  TAUD1.CMOR14.BIT.MD0 	= 1;						/* 開始時割り込み発生		*/
	TAUD1.CMOR14.UINT16		= 0x0801 ;	
	
	/* スレーブ（Duty制御）								*/
//	TAUD1.CMOR15.BIT.CKS	= 0;						/* 動作クロック（CK3）		*/
//	TAUD1.CMOR15.BIT.CCS	= 0;						/* カウントクロック(CKSによる）	*/	
//	TAUD1.CMOR15.BIT.MAS	= 0;						/* スレーブ					*/			
//	TAUD1.CMOR15.BIT.STS	= 4;						/* マスタの割り込みトリガ	*/
//	TAUD1.CMOR15.BIT.COS	= 0;						/*							*/	
//	TAUD1.CMOR15.BIT.MD 	= 4;						/* ワンカウントモード		*/
//  TAUD1.CMOR15.BIT.MD0 	= 1;						/* 開始時割り込み発生		*/
	TAUD1.CMOR15.UINT16		= 0x0409 ;		

	/*-------------------------------------------------*/
	/* Channel Mode User Register                      */
	/*-------------------------------------------------*/
	TAUD1.CMUR14.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */
	TAUD1.CMUR15.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */

	
	/*-------------------------------------------------*/
	/* Channel Status Clear Register                   */
	/*-------------------------------------------------*/
	TAUD1.CSC14.UINT8 		= 1;							/* OVFフラグクリア 				*/	
	TAUD1.CSC15.UINT8 		= 1;							/* OVFフラグクリア 				*/	
	

	/*-------------------------------------------------*/
	/*  Channel Counter Register 					   */
	/*-------------------------------------------------*/
	TAUD1.CNT14 = 0;
	TAUD1.CNT15 = 0;

	/*-------------------------------------------------*/
	/* Channel Data Register      	            	   */
	/*-------------------------------------------------*/
	/* 周期設定											*/
	{
		double t_CMP	= ((double)(__CLKC_HSB*1e6))/((double)u4_freq);
		if(t_CMP>65535.)
		{
			TAUD1.CDR14		= 65535;
		}
		else
		{
			TAUD1.CDR14		= (u2)t_CMP ;
		}
	}	
	
								
	/* Duty設定											*/
	TAUD1.CDR15 = 0;										
	
	/*============== TAUD1 各チャネル一括	=================*/
	/*-------------------------------------------------*/
	/* Channel Output Enable Register                  */
	/*-------------------------------------------------*/
	TAUD1.TOE.UINT16		|= 0x8000;					/* 出力許可						 */

	/*-------------------------------------------------*/
	/* Channel Output Mode Register                    */
	/*-------------------------------------------------*/
	TAUD1.TOM.UINT16 		|= 0x8000;						/* チャネル連動動作				 */

	/*-------------------------------------------------*/
	/* Channel Output Configuration Register           */
	/*-------------------------------------------------*/
	TAUD1.TOC.UINT16		&= ~0x8000;						/* 動作モード1					 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Enable Register         */
	/*-------------------------------------------------*/
	if ( 0 == u1_logic )
	{
		TAUD1.TOL.UINT16		&= ~0x8000;						/* アクティブレベルHI			 */
		PORT.P1.BIT.P1_15		= 0;
	}
	else
	{
		TAUD1.TOL.UINT16		|= 0x8000;						/* アクティブレベルHI			 */
		PORT.P1.BIT.P1_15		= 1;
	}
	/*-------------------------------------------------*/
	/* Channel DeadTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD1.TDE.UINT16 		&= ~0x8000;						/* デットタイム動作禁止			 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Mode                    */
	/*-------------------------------------------------*/
	TAUD1.TDM.UINT16	 	&= ~0x8000;						/* 偶数チャネル					 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Level                   */
	/*-------------------------------------------------*/
	TAUD1.TDL.UINT16		&= ~0x8000;						/* 正相にデットタイム付加		 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD1.TRE.UINT16		&= ~0x8000;						/* リアルタイム出力禁止			 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Register                */
	/*-------------------------------------------------*/
	TAUD1.TRO.UINT16 		&= ~0x8000;						/* TRO出力 LOW					*/

	/*-------------------------------------------------*/
	/* Channel RealTime Output Control Register        */
	/*-------------------------------------------------*/
	TAUD1.TRC.UINT16 		&= ~0x8000;						/* リアルタイム出力生成トリガ選択 */

	/*-------------------------------------------------*/
	/* Channel modulation output enable Register       */
	/*-------------------------------------------------*/
	TAUD1.TME.UINT16		&= ~0x8000;						/* 変調禁止							*/
	
	/*-------------------------------------------------*/
	/* 一斉書き換え関連レジスタ設定				      */
	/*-------------------------------------------------*/
	TAUD1.RDE.UINT16		|= 0xC000;						/* 一斉書き換え許可					*/	
	TAUD1.RDS.UINT16		&= ~0xC000;						/* マスタチャネルの一斉トリガ発生	*/	
	TAUD1.RDM.UINT16		&= ~0xC000;						/* マスタチャネルがカウント開始でトリガ発生					*/	
	TAUD1.RDC.UINT16		&= ~0xC000;						/* 一斉書き換えトリガとして動作しない*/	
	/*====================================================*/

	/* 割り込みレベル設定	*/
	/* TAUD1 CH14			*/
	if ( 2 ==  u1_intcpu )
	{
		INTC2.EIBD112.BIT.GPID	= 1;							/* CPU2にバインド					*/
		INTC2.EIBD112.BIT.PEID	= 2;							/* CPU2にバインド					*/
	}
	else
	{
		INTC2.EIBD112.BIT.GPID	= 0;							/* CPU1にバインド					*/
		INTC2.EIBD112.BIT.PEID	= 1;							/* CPU1にバインド					*/		
	}
	if( u1_intlv < 16 )
	{
		INTC2.EIC112.BIT.EIRF112	= 0 ;						/* 割り込みフラグクリア				*/
		INTC2.EIC112.BIT.EIP112		= u1_intlv ;				/* 割り込みレベル設定				*/
		INTC2.EIC112.BIT.EITB112	= 1;						/* テーブル参照方式					*/
//		INTC2.EIC112.BIT.EITB112	= 0;						/* 直接分岐方式						*/
		INTC2.EIC112.BIT.EIMK112	= 0 ;						/* 割り込みマスククリア				*/
	}
	else
	{
		INTC2.EIC112.BIT.EIMK112	= 1 ;						/* 割り込みマスク					*/
	}

}

