/*==============================================================*/
/*	TAUJ0用クロック初期化関数									*/
/*	引数：														*/
/*			なし												*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*			制御タイマ：TAUJ0									*/
/*			CK0	= PCLK											*/
/*			CK1 = PCLK/2										*/
/*			CK2 = PCLK/8										*/
/*			CK3_PRE = PCLK										*/
/*			CK3	= 1MHzになるように設定							*/
/*			TAUJ0が停止中に実行の事								*/
/*--------------------------------------------------------------*/
void	tauj0prescale0_2_8_0_init(void)
{
	/*-------------------------------------------------*/
	/* Set Clock Frequency                             */
	/*-------------------------------------------------*/
//	TAUJ0.TPS = 0b0000 00010 0001 0000;				/* Prescaler Clock Select */
	TAUJ0.TPS.UINT16 = 0x0310;

/*							CK3_PRE[15-12] = PCLK/2^0
							CK2[11- 8]     = PCLK/2^3
							CK1[ 7- 4]     = PCLK/2^1
							CK0[ 3- 0]     = PCLK/2^0
*/
	/*-------------------------------------------------*/
	/* Set Baudrate  CK3 = CK3PRE/BRS                  */
	/*-------------------------------------------------*/
	TAUJ0.BRS			= (u4)(__CLKC_HSB)-1;		/* CK3_PRE/(TAUJ0BRS+1)=1MHz */
	
}

/*==============================================================*/
/*	TAUJ0全CH停止関数											*/
/*	引数：														*/
/*			なし												*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*--------------------------------------------------------------*/
void	tauj0_stop(void)
{
	TAUJ0.TT.UINT8 = 0x0F;					/* 全TAUD0タイマ停止		*/
}

/*==============================================================*/
/*	PWMタイマ0_2初期化関数										*/
/*	引数：														*/
/*			u4	u4_freq	: PWM周期[Hz]							*/
/*			u1	u1_logic :PWM論理	0:正論理　それ以外:負論理	*/
/*			u1 u1_intlv	:割り込みレベル							*/
/*			u1 u1_intcpu: 2: PE2 /2以外:PE1						*/
/*																*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUJ0_CH0/2				*/
/*							プリスケーラクロック CK0を選択		*/
/*				出力端子	: P0_2								*/
/*	注意！！　CK0の分解能は、80MHzになっている事				*/
/*--------------------------------------------------------------*/
void pwm0_2_init ( u4 u4_freq , u1 u1_logic , u1 u1_intlv , u1 u1_intcpu)
{
	
	/* PWM出力端子Hi-z	*/
	{		
		u4 t_PMSR0	= (((0x1)<<2)<<16) | (0x1<<2);				/* PM0_2			 入力モード		*/
		u4 t_PMCSR0	= (((0x1)<<2)<<16) | (0x0<<2);				/* PMC0_2			 ポートモード	*/

		PORT.PMSR0.UINT32	= t_PMSR0;
		PORT.PMCSR0.UINT32	= t_PMCSR0;	
	}

	/*-------------------------------------------------*/
	/* 　TAUJ0 CH0/2停止 			                   */
	/*-------------------------------------------------*/
	TAUJ0.TT.UINT8 		= 0x05;						/* CH0/2 STOP					*/

	/* PWM周波数設定*/
	{
		double t_CMP0	= ((double)(__CLKC_HSB*1e6))/((double)u4_freq);
		if(t_CMP0>65535.)
		{
			TAUJ0.CDR0		= (u4)65535;
		}
		else
		{
			TAUJ0.CDR0		= (u4)t_CMP0-1 ;
		}
	}
	
	/* Duty 設定	 0%*/
	TAUJ0.CDR2	= 0;

	/*-------------------------------------------------*/
	/*  Channel Counter Register 					   */
	/*-------------------------------------------------*/
	TAUJ0.CNT0 = 0;
	TAUJ0.CNT2 = 0;

	/*-------------------------------------------------*/
	/* Channel ModeOS Register	                  		*/
	/*-------------------------------------------------*/
	TAUJ0.CMOR0.UINT16		= 0x0801 ;
	TAUJ0.CMOR2.UINT16		= 0x0409 ;
	/*-------------------------------------------------*/
	/* Channel Mode User Register                      */
	/*-------------------------------------------------*/
	TAUJ0.CMUR0.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */
	TAUJ0.CMUR2.UINT8		= 0;
	/*-------------------------------------------------*/
	/* Channel Status Clear Register                   */
	/*-------------------------------------------------*/
	TAUJ0.CSC0.UINT8 		= 1;							/* OVFフラグクリア 				*/
	TAUJ0.CSC2.UINT8 		= 1;							/* OVFフラグクリア 				*/
/*============== TAUJ0 各チャネル一括	=================*/
	/*-------------------------------------------------*/
	/* Channel Output Enable Register                  */
	/*-------------------------------------------------*/
	TAUJ0.TOE.UINT8		|= 0x4;							/* CH2出力許可						 */

	/*-------------------------------------------------*/
	/* Channel Output Mode Register                    */
	/*-------------------------------------------------*/
	TAUJ0.TOM.UINT8 	&= ~0x1;						/* CH0チャネル単体動作				 */
	TAUJ0.TOM.UINT8		|= 0x4;							/* CH2チャネル連動動作				 */
	/*-------------------------------------------------*/
	/* Channel Output Configuration Register           */
	/*-------------------------------------------------*/
	TAUJ0.TOC.UINT8		&= ~0x5;						/* CH0/2トグルモード				 */

	/*-------------------------------------------------*/
	/* Channel  Output Level Register   		       */
	/*-------------------------------------------------*/
	if ( 0 == u1_logic )
	{
		TAUJ0.TOL.UINT8		&= ~0x4;						/* アクティブレベルHI				 */
	}
	else
	{
		TAUJ0.TOL.UINT8		|= 0x4;							/* アクティブレベルLow				 */
	}
	/*-------------------------------------------------*/

	/*-------------------------------------------------*/
	/* Channel  Output Register     		           */
	/*-------------------------------------------------*/
	TAUJ0.TO.UINT8 	&= ~0x5;							/* TO出力 LOW						*/

	TAUJ0.RDE.UINT8	|=  0x5;							/* 一斉書き換え許可					*/
	TAUJ0.RDM.UINT8	&= ~0x5;


	/* 割り込みレベル設定	*/
	if ( 2 == u1_intcpu )
	{
		INTC2.EIBD78.BIT.GPID	= 1;							/* CPU2にバインド					*/
		INTC2.EIBD78.BIT.PEID	= 2;							/* CPU2にバインド					*/
	}
	else
	{
		INTC2.EIBD78.BIT.GPID	= 0;							/* CPU1にバインド					*/
		INTC2.EIBD78.BIT.PEID	= 1;							/* CPU1にバインド					*/
	}
	if( u1_intlv < 16 )
	{
		INTC2.EIC78.BIT.EIRF78	= 0 ;						/* 割り込みフラグクリア				*/
		INTC2.EIC78.BIT.EIP78	= u1_intlv ;				/* 割り込みレベル設定				*/
		INTC2.EIC78.BIT.EITB78	= 1;						/* テーブル参照方式					*/
//		INTC2.EIC78.BIT.EITB78	= 0;						/* 直接分岐方式						*/
		INTC2.EIC78.BIT.EIMK78	= 0 ;						/* 割り込みマスククリア				*/
	}
	else
	{
		INTC2.EIC78.BIT.EIMK78	= 1 ;						/* 割り込みマスク					*/
	}

	/*====================================================*/
	/*	ポート設定		*/
	/* P0_2 第2兼用選択	*/
	PORT.PCR0_2.UINT32	= 0x00000011;					/* PORT0_2 TAUJ0O2						*/
														/* PM 	 = 1							*/
														/* PMC1  = 0							*/
														/* PFCAE = 0							*/
														/* PFCE  = 0							*/
														/* PFC   = 1							*/
}

