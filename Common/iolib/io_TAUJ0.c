/*==============================================================*/
/*	TAUJ0O2 PWMDuty設定関数(浮動少数点Ver）						*/
/*	引数：	f4 f4_m : PWMDuty( 0 ~ +1 )							*/
/*  戻り値：なし												*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*			出力ピン											*/
/*					: P0_2/TAUJ0O2								*/
/*==============================================================*/
void set_pwm0_2_m ( f4 f4_m )
{
	f4 t_f4_m ;
	f4 f4_m_t ;
	u4 u4_m_t ;
	
	t_f4_m = f4_m ;
	
	if ( t_f4_m >= 1.0F )
	{
		u4_m_t = TAUJ0.CDR0+1 ;
	}
	else
	{
		if ( t_f4_m <= 0.0F )
		{
			u4_m_t = (u4)(0) ;
		}
		else
		{
			f4_m_t = t_f4_m * (f4)(TAUJ0.CDR0);
			u4_m_t = (u4)(f4_m_t) ;
		}
	}
	
	TAUJ0.CDR2		= u4_m_t;
	TAUJ0.RDT.UINT8	= 0x05;			//  リロード許可
}

/*==============================================================*/
/*	TAUJ0O2 PWMDuty設定関数(浮動少数点Ver）						*/
/*	引数：	f4 f4_m : PWMDuty( 0 ~ +1 )							*/
/*			f4 u4_freq : PWM周波数（Hz)							*/ 
/*  戻り値：なし												*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*			出力ピン											*/
/*					: P0_2/TAUJ0O2								*/
/*==============================================================*/
void set_pwm0_2_mf ( f4 f4_m  , f4 f4_freq )
{
	f4 t_f4_m ;
	f4 f4_m_t ;
	u4 u4_m_t ;
	f4	t_f4_freq ;
	
	t_f4_m = f4_m ;

	t_f4_freq = f4_freq ;

	if ( 0 == t_f4_freq )
	{
		t_f4_freq = 1 ;
	}

	{
		double t_CMP0	= ((double)(__CLKC_HSB*1e6))/((double)t_f4_freq);
		if(t_CMP0>65535.)
		{
			TAUJ0.CDR0		= (u4)65535;
		}
		else
		{
			TAUJ0.CDR0		= (u4)t_CMP0-1 ;
		}
	}

	
	if ( t_f4_m >= 1.0F )
	{
		u4_m_t = TAUJ0.CDR0+1 ;
	}
	else
	{
		if ( t_f4_m <= 0.0F )
		{
			u4_m_t = (u4)(0) ;
		}
		else
		{
			f4_m_t = t_f4_m * (f4)(TAUJ0.CDR0);
			u4_m_t = (u4)(f4_m_t) ;
		}
	}
	
	TAUJ0.CDR2		= u4_m_t;
	TAUJ0.RDT.UINT8	= 0x05;			//  リロード許可
}

