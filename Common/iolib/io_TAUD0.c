/*			u4	u4_interval_us	: インターバル時間[uS]			*/
/*			u1	u1_intlv		:割り込みレベル					*/
/*			u1 u1_intcpu	: 2: PE2 /2以外:PE1					*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUD0_CH0				*/
/*							プリスケーラクロック CK3を選択		*/
/*	注意！！　CK3の分解能は、1uSになっている事					*/
/*--------------------------------------------------------------*/

/*=============================================================*/
/*	TAUD0初期化関数（タイマ割り込み）						   */
/*=============================================================*/
void interval00_init ( u4 u4_interval_us, u1 u1_intlv , u1 u1_intcpu)
{
	/*-------------------------------------------------*/
	/* 　TAUD0 CH0停止 			                      */
	/*-------------------------------------------------*/
	TAUD0.TT.UINT16 		= 1;						/* CH0 STOP					*/

	/*-------------------------------------------------*/
	/* Channel Data Register      	            	   */
	/*-------------------------------------------------*/
	TAUD0.CDR0 = u4_interval_us - 1;

	/*-------------------------------------------------*/
	/*  Channel Counter Register 			   */
	/*-------------------------------------------------*/
	TAUD0.CNT0 = u4_interval_us - 1;

	/*-------------------------------------------------*/
	/* Channel ModeOS Register	                  		*/
	/*-------------------------------------------------*/
//	TAUD0.CMOR0.BIT.CKS	= 3;						/* 動作クロック（CK3）		*/
//	TAUD0.CMOR0.BIT.CCS	= 0;						/* カウントクロック(CKSによる）	*/	
//	TAUD0.CMOR0.BIT.MAS	= 0;						/* スレーブ					*/			
//	TAUD0.CMOR0.BIT.STS	= 0;						/* ソフトウェアトリガ		*/
//	TAUD0.CMOR0.BIT.COS	= 0;						/*							*/	
//	TAUD0.CMOR0.BIT.MD 	= 0;						/* インターバルタイマモード	*/

	TAUD0.CMOR0.UINT16		= 0xC000 ;

	/*-------------------------------------------------*/
	/* Channel Mode User Register                      */
	/*-------------------------------------------------*/
	TAUD0.CMUR0.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */
	
	/*-------------------------------------------------*/
	/* Channel Status Clear Register                   */
	/*-------------------------------------------------*/
	TAUD0.CSC0.UINT8 		= 1;							/* OVFフラグクリア 				*/

	/*============== TAUD0 各チャネル一括	=================*/

	/*-------------------------------------------------*/
	/* Channel Output Enable Register                  */
	/*-------------------------------------------------*/
	TAUD0.TOE.UINT16		&= ~0x1;						/* 出力禁止						 */

	/*-------------------------------------------------*/
	/* Channel Output Mode Register                    */
	/*-------------------------------------------------*/
	TAUD0.TOM.UINT16 		&= ~0x1;						/* チャネル単体動作				 */

	/*-------------------------------------------------*/
	/* Channel Output Configuration Register           */
	/*-------------------------------------------------*/
	TAUD0.TOC.UINT16		&= ~0x1;						/* トグルモード					 */

	/*-------------------------------------------------*/
	/* Channel  Output Level Register   		       */
	/*-------------------------------------------------*/
	TAUD0.TOL.UINT16		&= ~0x1;						/* アクティブレベルHI			 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD0.TDE.UINT16 		&= ~0x1;						/* デットタイム動作禁止			 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Mode                    */
	/*-------------------------------------------------*/
	TAUD0.TDM.UINT16	 	&= ~0x1;						/* 偶数チャネル					 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Level                   */
	/*-------------------------------------------------*/
	TAUD0.TDL.UINT16		&= ~0x1;						/* 正相にデットタイム付加		 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD0.TRE.UINT16		&= ~0x1;						/* リアルタイム出力禁止			 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Register                */
	/*-------------------------------------------------*/
	TAUD0.TRO.UINT16 		&= ~0x1;						/* TRO出力 LOW					*/

	/*-------------------------------------------------*/
	/* Channel RealTime Output Control Register        */
	/*-------------------------------------------------*/
	TAUD0.TRC.UINT16 		&= ~0x1;						/* リアルタイム出力生成トリガ選択 */

	/*-------------------------------------------------*/
	/* Channel modulation output enable Register       */
	/*-------------------------------------------------*/
	TAUD0.TME.UINT16		&= ~0x0001;						/* 変調禁止							*/
	/*====================================================*/

	/* 割り込みレベル設定	*/
	if ( 2 == u1_intcpu )
	{
		INTC2.EIBD82.BIT.GPID	= 1;							/* CPU2にバインド					*/
		INTC2.EIBD82.BIT.PEID	= 2;							/* CPU2にバインド					*/
	}
	else
	{
		INTC2.EIBD82.BIT.GPID	= 0;							/* CPU1にバインド					*/
		INTC2.EIBD82.BIT.PEID	= 1;							/* CPU1にバインド					*/
	}
	if( u1_intlv < 16 )
	{
		INTC2.EIC82.BIT.EIRF82	= 0 ;						/* 割り込みフラグクリア				*/
		INTC2.EIC82.BIT.EIP82	= u1_intlv ;				/* 割り込みレベル設定				*/
		INTC2.EIC82.BIT.EITB82	= 1;						/* テーブル参照方式					*/
//		INTC2.EIC82.BIT.EITB82	= 0;						/* 直接分岐方式						*/
		INTC2.EIC82.BIT.EIMK82	= 0 ;						/* 割り込みマスククリア				*/
	}
	else
	{
		INTC2.EIC82.BIT.EIMK82	= 1 ;						/* 割り込みマスク					*/
	}

}

