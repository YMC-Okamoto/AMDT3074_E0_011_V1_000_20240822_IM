/*==============================================================*/
/*	TAUD0用クロック初期化関数									*/
/*	引数：														*/
/*			なし												*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*			制御タイマ：TAUD0									*/
/*			CK0	= CLKC_HSB										*/
/*			CK1 = CLKC_HSB/2^1									*/
/*			CK2 = CLKC_HSB/2^3									*/
/*			CK3_PRE = CLKC_HSB									*/
/*			CK3	= 1MHzになるように設定							*/
/*			TAUD0が停止中に実行の事								*/
/*--------------------------------------------------------------*/
void	taud0prescale_0_2_8_0_init(void)
{
	/*-------------------------------------------------*/
	/* Set Clock Frequency                             */
	/*-------------------------------------------------*/
	TAUD0.TPS.UINT16 = 0x0310;			/* Prescaler Clock Select */

/*							CK3_PRE[15-12] = PCLK/2^0
							CK2[11- 8]     = PCLK/2^3
							CK1[ 7- 4]     = PCLK/2^1
							CK0[ 3- 0]     = PCLK/2^0
*/
	/*-------------------------------------------------*/
	/* Set Baudrate  CK3 = CK3PRE/BRS                  */
	/*-------------------------------------------------*/
	TAUD0.BRS			= (u4)(__CLKC_HSB)-1;		/* CK3_PRE/(TAUD0BRS+1)=1MHz */
	
}

