/*==============================================================*/
/*　PWMタイマタイマ0_7変調率設定関数								*/
/*	引数：	f4		f4_m :PWM変調率　　0~1.0					*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUD0_CH6/7				*/
/*--------------------------------------------------------------*/	
void pwm0_7_setm_f ( f4 f4_m )
{
	u2	u2_cnt_m;
	
	if ( f4_m >= 1.0 )
	{
		u2_cnt_m = (u2)(TAUD0.CDR6+1) ;
	}
	else
	{
		if ( f4_m <= 0 )
		{
			u2_cnt_m = (u2)(0);
		}
		else
		{
			u2_cnt_m = (u2)(f4_m * (f4)(TAUD0.CDR6));
		}
	}

	TAUD0.CDR7	= (u2)u2_cnt_m;	
	TAUD0.RDT.UINT16  = 0x00C0 ;		/* CH6/7 リロード許可		*/
}		
