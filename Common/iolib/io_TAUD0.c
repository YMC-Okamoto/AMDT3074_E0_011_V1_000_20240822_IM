/*==============================================================*/
/*	TAUD　キャプチャタイマリード								*/
/*	引数：	なし												*/
/*	　　　　使用周辺機能	TAUD0/CH6-11,TAUD1/CH6-11			*/
/*	戻り値：													*/
/*			0 :オーバーフローなし(周期、Dutyとも)				*/
/*			1 :Dutyオーバー										*/
/*			2 :周期オバーフロー									*/
/*			3 :Dutyと周期両方オーバーフロー						*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*			TAUD0 CHx:Hi幅測定									*/
/*			TAUD1 CHx:周期測定									*/
/*==============================================================*/
u1	temp_capture6_read( u2 *u2_freq_cnt , u2 *u2_hilevel_cnt)
{
	u2	u2_freq_cnt_cap;
	u2	u2_duty_cnt_cap;
	u1	u1_ovf = 0 ;
	
	u1_ovf	= ( (TAUD0.CSR6.UINT8 & 0x01) << 1 )| (TAUD1.CSR6.UINT8 & 0x01);

	if ( 0 == (TAUD1.CSR6.UINT8 & 0x01) ) 					/* オーバーフローなし								*/
	{
		u2_duty_cnt_cap = TAUD1.CDR6 ;	
	}
	else												/* オーバーフローした								*/
	{
		u2_duty_cnt_cap = 0xFFFF ;						/* オーバーフローした時は、FFFFを返して上位側で無視	*/
		TAUD1.CSC6.UINT8 = 1 ;
	}

	if ( 0 ==  (TAUD0.CSR6.UINT8 & 0x01) ) 									/* オーバーフローなし						*/
	{
		u2_freq_cnt_cap = TAUD0.CDR6 ;	
	}
	else												/* オーバーフローした						*/
	{
		u2_freq_cnt_cap = 0xFFFF ;						/* オーバーフローした時は、FFFFを返して上位側で無視	*/
		TAUD0.CSC6.UINT8 = 1 ;
	}

	*u2_freq_cnt 	= u2_freq_cnt_cap ;
	*u2_hilevel_cnt = u2_duty_cnt_cap ;
	
	return (u1_ovf);	
	
}

