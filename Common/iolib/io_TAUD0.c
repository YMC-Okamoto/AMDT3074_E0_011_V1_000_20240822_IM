/*==============================================================*/
/*	PWM1タイマ0_7初期化関数										*/
/*	引数：														*/
/*			u4 u4_freq			:キャリア周波数[Hz]				*/
/*			u1 u1_logic			:PWM論理	0:正論理　それ以外:負論理	*/
/*			u1	u1_intlv		:割り込みレベル					*/
/*			u1 u1_intcpu	: 2: PE2 /2以外:PE1					*/
/*--------------------------------------------------------------*/
/*	備考														*/
/*	　　　　使用周辺機能										*/
/*							制御タイマ：TAUD0_CH6/7				*/
/*							P3_1/TAUD0O7						*/
/*							プリスケーラクロック CK0を選択		*/
/*	注意！！　CK0の分解能は、12.5nSになっている事				*/
/*--------------------------------------------------------------*/
void pwm0_7_init (  u4 u4_freq, u1 u1_logic ,u1 u1_intlv  , u1 u1_intcpu )
{
	/*-------------------------------------------------*/
	/* 　P3_1入力モード   			                   */
	/*-------------------------------------------------*/
	PORT.PCR3_1.UINT32		=	0x00000010;				/* 入力		*/
	
	/*-------------------------------------------------*/
	/* 　TAUD0 CH6,7停止 			                      */
	/*-------------------------------------------------*/
	TAUD0.TT.UINT16 		= 0x00C0;					/* CH6,7 STOP					*/

	
	/*-------------------------------------------------*/
	/* Channel ModeOS Register	                  		*/
	/*-------------------------------------------------*/	
	/* マスタ（周期制御	）								*/
//	TAUD0.CMOR6.BIT.CKS	= 0;						/* 動作クロック（CK3）		*/
//	TAUD0.CMOR6.BIT.CCS	= 0;						/* カウントクロック(CKSによる）	*/	
//	TAUD0.CMOR6.BIT.MAS	= 1;						/* マスタ					*/			
//	TAUD0.CMOR6.BIT.STS	= 0;						/* ソフトウェアトリガ		*/
//	TAUD0.CMOR6.BIT.COS	= 0;						/*							*/	
//	TAUD0.CMOR6.BIT.MD 	= 0;						/* インターバルタイマモード	*/
//  TAUD0.CMOR6.BIT.MD0 = 1;						/* 開始時割り込み発生		*/
	TAUD0.CMOR6.UINT16	= 0x0801 ;	
	
	/* スレーブ（Duty制御）								*/
//	TAUD0.CMOR7.BIT.CKS	= 0;						/* 動作クロック（CK3）		*/
//	TAUD0.CMOR7.BIT.CCS	= 0;						/* カウントクロック(CKSによる）	*/	
//	TAUD0.CMOR7.BIT.MAS	= 0;						/* スレーブ					*/			
//	TAUD0.CMOR7.BIT.STS	= 4;						/* マスタの割り込みトリガ	*/
//	TAUD0.CMOR7.BIT.COS	= 0;						/*							*/	
//	TAUD0.CMOR7.BIT.MD 	= 4;						/* ワンカウントモード		*/
//  TAUD0.CMOR7.BIT.MD0 = 1;						/* 開始時割り込み発生		*/
	TAUD0.CMOR7.UINT16	= 0x0409 ;		

	/*-------------------------------------------------*/
	/* Channel Mode User Register                      */
	/*-------------------------------------------------*/
	TAUD0.CMUR6.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */
	TAUD0.CMUR7.UINT8 		= 0; 							/* 立下り選択（意味なし）		 */

	
	/*-------------------------------------------------*/
	/* Channel Status Clear Register                   */
	/*-------------------------------------------------*/
	TAUD0.CSC6.UINT8 		= 1;							/* OVFフラグクリア 				*/	
	TAUD0.CSC7.UINT8 		= 1;							/* OVFフラグクリア 				*/	
	

	/*-------------------------------------------------*/
	/*  Channel Counter Register 					   */
	/*-------------------------------------------------*/
	TAUD0.CNT6 = 0;
	TAUD0.CNT7 = 0;

	/*-------------------------------------------------*/
	/* Channel Data Register      	            	   */
	/*-------------------------------------------------*/
	/* 周期設定											*/
	{
		double t_CMP	= ((double)(__CLKC_HSB*1e6))/((double)u4_freq);
		if(t_CMP>65535.)
		{
			TAUD0.CDR6		= 65535;
		}
		else
		{
			TAUD0.CDR6		= (u2)t_CMP ;
		}
	}	
	
								
	/* Duty設定											*/
	TAUD0.CDR7 = 0;										
	
	/*============== TAUD0 各チャネル一括	=================*/
	/*-------------------------------------------------*/
	/* Channel Output Enable Register                  */
	/*-------------------------------------------------*/
	TAUD0.TOE.UINT16		|= 0x0080;					/* 出力許可						 */

	/*-------------------------------------------------*/
	/* Channel Output Mode Register                    */
	/*-------------------------------------------------*/
	TAUD0.TOM.UINT16 		|= 0x0080;						/* チャネル連動動作				 */

	/*-------------------------------------------------*/
	/* Channel Output Configuration Register           */
	/*-------------------------------------------------*/
	TAUD0.TOC.UINT16		&= ~0x0080;						/* 動作モード1					 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Enable Register         */
	/*-------------------------------------------------*/
	if ( 0 == u1_logic )
	{
		TAUD0.TOL.UINT16		&= ~0x0080;						/* アクティブレベルHI			 */
		PORT.P6.BIT.P6_7		= 0;
	}
	else
	{
		TAUD0.TOL.UINT16		|= 0x0080;						/* アクティブレベルHI			 */
		PORT.P6.BIT.P6_7		= 1;
	}
	/*-------------------------------------------------*/
	/* Channel DeadTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD0.TDE.UINT16 		&= ~0x0080;						/* デットタイム動作禁止			 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Mode                    */
	/*-------------------------------------------------*/
	TAUD0.TDM.UINT16	 	&= ~0x0080;						/* 偶数チャネル					 */

	/*-------------------------------------------------*/
	/* Channel DeadTime Output Level                   */
	/*-------------------------------------------------*/
	TAUD0.TDL.UINT16		&= ~0x0080;						/* 正相にデットタイム付加		 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Enable Register         */
	/*-------------------------------------------------*/
	TAUD0.TRE.UINT16		&= ~0x0080;						/* リアルタイム出力禁止			 */

	/*-------------------------------------------------*/
	/* Channel RealTime Output Register                */
	/*-------------------------------------------------*/
	TAUD0.TRO.UINT16 		&= ~0x0080;						/* TRO出力 LOW					*/

	/*-------------------------------------------------*/
	/* Channel RealTime Output Control Register        */
	/*-------------------------------------------------*/
	TAUD0.TRC.UINT16 		&= ~0x0080;						/* リアルタイム出力生成トリガ選択 */

	/*-------------------------------------------------*/
	/* Channel modulation output enable Register       */
	/*-------------------------------------------------*/
	TAUD0.TME.UINT16		&= ~0x0080;						/* 変調禁止							*/
	
	/*-------------------------------------------------*/
	/* 一斉書き換え関連レジスタ設定				      */
	/*-------------------------------------------------*/
	TAUD0.RDE.UINT16		|= 0x00C0;						/* 一斉書き換え許可					*/	
	TAUD0.RDS.UINT16		&= ~0x00C0;						/* マスタチャネルの一斉トリガ発生	*/	
	TAUD0.RDE.UINT16		&= ~0x00C0;						/* マスタチャネルがカウント開始でトリガ発生					*/	
	TAUD0.RDE.UINT16		&= ~0x00C0;						/* 一斉書き換えトリガとして動作しない*/	
	/*====================================================*/

	/* 割り込みレベル設定	*/
	/* TAUD0 CH6			*/
	if ( 2 ==  u1_intcpu )
	{
		INTC2.EIBD88.BIT.GPID	= 1;							/* CPU2にバインド					*/
		INTC2.EIBD88.BIT.PEID	= 2;							/* CPU2にバインド					*/
	}
	else
	{
		INTC2.EIBD88.BIT.GPID	= 0;							/* CPU1にバインド					*/
		INTC2.EIBD88.BIT.PEID	= 1;							/* CPU1にバインド					*/		
	}
	if( u1_intlv < 16 )
	{
		INTC2.EIC88.BIT.EIRF88	= 0 ;						/* 割り込みフラグクリア				*/
		INTC2.EIC88.BIT.EIP88	= u1_intlv ;				/* 割り込みレベル設定				*/
		INTC2.EIC88.BIT.EITB88	= 1;						/* テーブル参照方式					*/
//		INTC2.EIC88.BIT.EITB88	= 0;						/* 直接分岐方式						*/
		INTC2.EIC88.BIT.EIMK88	= 0 ;						/* 割り込みマスククリア				*/
	}
	else
	{
		INTC2.EIC88.BIT.EIMK88	= 1 ;						/* 割り込みマスク					*/
	}

}

