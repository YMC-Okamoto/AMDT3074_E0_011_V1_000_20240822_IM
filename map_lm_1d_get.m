function lm = map_lm_1d_get(id_ref)
% map_lm_1d_get
% d軸電流 |id| に対する励磁インダクタンス Lm を、1次元マップから取得する関数
%
% 【この関数の目的】
% 誘導機では電流が大きくなると磁気飽和により Lm（励磁インダクタンス）が低下します。
% 本関数はその非線形特性を「テーブル（マップ）」で表現し、
% 与えられた d軸電流指令 id_ref に対応する Lm を補間計算で返します。
%
% 【組み込みコード対応】
%   - PE1/src/mapdata_lm_inv0_1d.c      : u1_lm_map_1d_get()
%   - PE1/src/mapdata_lm_inv0_1d_map.c  : 生テーブルデータ
%
% 【軸定義（組み込みヘッダ準拠）】
%   N_X_2_1D      = 257   （サンプル点数）
%   ORIGIN_X_2_1D = 0     （軸原点）
%   RESO_X_2_1D   = 4     （軸分解能、単位は id_ref と同じ[A]）
%
% 【重要な挙動メモ】
%   |id| < 148A（= 37*4）付近までは、Lm はほぼ一定値 0.000210869 [H] です。
%   したがって通常運転域（例: |id| < 約17.3A）では、
%   マップを使っても実質的に公称値と同等になります。
%   非線形な飽和効果が強く出るのは高電流域です。
%
% 【入力】
%   id_ref : d軸電流指令 [A]
%
% 【出力】
%   lm     : 補間後の励磁インダクタンス [H]

    % persistent を使う理由：
    % テーブルは毎回生成すると無駄なため、最初の1回だけ作成して保持します。
    persistent MAP_LM
    if isempty(MAP_LM)
        MAP_LM = lm_table();   % 初回のみテーブル初期化
    end

    % 軸情報（組み込み定義と同じ値）
    N_X    = 257;  % テーブル点数
    ORIGIN = 0;    % 軸原点
    RESO   = 4;    % 1インデックス当たりの電流幅 [A]

    % ---------------------------------------------------------------
    % 1) 連続値の軸位置 x_nom を計算
    % ---------------------------------------------------------------
    % マップ入力は |id| を使います（正負対称のため）。
    % x_nom は「テーブル上の実数インデックス」に相当します。
    x_nom = (abs(id_ref) - ORIGIN) / RESO;

    % マップ範囲外アクセスを防ぐため、[0, N_X-1] に制限
    x_nom = max(0, min(N_X - 1, x_nom));

    % ---------------------------------------------------------------
    % 2) 線形補間のための下側インデックス xi と重み kw を算出
    % ---------------------------------------------------------------
    xi = floor(x_nom);      % 下側インデックス（0始まり）
    xi = min(xi, N_X - 2);  % xi+1 を使うため上端保護
    kw = x_nom - xi;        % 補間重み（0～1）

    % ---------------------------------------------------------------
    % 3) 線形補間
    % ---------------------------------------------------------------
    % MATLAB配列は1始まりなので +1 補正して参照します。
    %   lm = (1-kw)*L(xi) + kw*L(xi+1)
    lm = (1-kw)*MAP_LM(xi+1) + kw*MAP_LM(xi+2);
    lm = lm * 1.5;
end

