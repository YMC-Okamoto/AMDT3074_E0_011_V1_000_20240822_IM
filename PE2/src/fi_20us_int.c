/*===============================================================
+																+
+				Name:		void fi_20usint (void)				+
+			Function:		20usタイマ割込み関数				+
+																+
+																+
+		Return Value:		No									+
+				date:		 10th Mar,2017						+
+																+
===============================================================*/
void fi_20us_int (void)
{

	/*============================================================*/
	/*						多重割り込み許可					　*/
	/*============================================================*/
	__EI();
	/*============================================================*/

	/*============================================================*/
	/*							デバッグ演算					　*/
	/*============================================================*/
	u1_cnt_20us_int_inv1++;
	/*============================================================*/

	/*============================================================*/
	/*							割込み禁止					　	  */
	/*============================================================*/
	__DI();
	/*============================================================*/
}

