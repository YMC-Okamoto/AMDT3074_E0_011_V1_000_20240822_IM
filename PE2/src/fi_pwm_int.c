void fi_pwm_int (void)
{

	/*============================================================*/
	/*			ADC1割込みフラグクリア(ForAD変換ウェイト)		  */
	/*============================================================*/
	Set_ADC1_SG4_IRF(0);										/* ADC1 SG4 割り込みフラグクリア */
	/*============================================================*/

	/*============================================================*/
	/*						多重割り込み許可					　*/
	/*============================================================*/
	__EI();
	/*============================================================*/

	/*============================================================*/
	/*							デバッグ演算					　*/
	/*============================================================*/
	u4_cnt_pwm_inv1++;
	/*============================================================*/

	/*============================================================*/
	/*				キャリア割込みWatcherデータ監視				　*/
	/*============================================================*/
	// VECLIB_CMDMONI_PWM();
	/*============================================================*/

	/*============================================================*/
	/*							割込み禁止					　	  */
	/*============================================================*/
	__DI();
	/*============================================================*/

}

