	/*============================================================*/
	
	/*============================================================*/
	/*				1ms/20usタイマスタート（CPU2)				　*/
	/*============================================================*/
	// interval10_start();	
	// interval12_start();
	/*============================================================*/

	/*============================================================*/
	/*					インバータタイマ開始					　*/
	/*============================================================*/
	// tsg31_start();												/* TSG31スタート								*/
	/*============================================================*/

	/*============================================================*/
	/*						初期化関数の実行					　*/
	/*============================================================*/
	fb_pwm_int_init();											/* キャリア割込み初期化関数						*/
	fb_1ms_int_init();											/* タイマ割込み初期化関数						*/

	fb_20us_int_init();											/* 20usタイマ割込み初期化関数					*/
