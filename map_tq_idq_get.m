% ---- 補助関数: 2次元双線形補間 ------------------------------------
function v = bilinear(M, yi1, yi2, xi1, xi2, kw_x, kw_y)
% 4点（左上・右上・左下・右下）から重み付き平均で中間値を計算します。
%
% 座標イメージ：
%   (yi1,xi1) ----x---- (yi1,xi2)
%       |                 |
%       y                 y
%       |                 |
%   (yi2,xi1) ----x---- (yi2,xi2)
%
% kw_x: x方向補間重み（0～1）
% kw_y: y方向補間重み（0～1）
    v = (1-kw_x)*(1-kw_y)*M(yi1,xi1) ...
      +    kw_x *(1-kw_y)*M(yi1,xi2) ...
      + (1-kw_x)*   kw_y *M(yi2,xi1) ...
      +    kw_x *   kw_y *M(yi2,xi2);
end