% im_vector_control_sim.m  —  シミュレーション実行用メインスクリプト
%
% 誘導電動機（IM: Induction Motor）のベクトル制御シミュレーションです。
% 組み込みソフトウェアの「二重周期タスク構成（Dual-rate）」を
% MATLAB上で再現することを目的としています。
%
% 再現している制御タスク構成：
%   ・100 µs のPWM割り込みタスク:
%       encctrl → idqctrl → svctrl → plant
%   ・1 ms のタイマタスク:
%       idqcom（トルク制限・電流指令生成）
%
% 使い方：
%   1) このスクリプトを MATLAB で直接実行してください。
%   2) パラメータは params_inv0.m から読み込みます。
%   3) トルク指令やシミュレーション時間を変えたい場合は、
%      下記「2. シナリオ設定」セクションを編集してください。
%
% 組み込みコードとの対応関係：
%   PE1/src/fi_pwm_inv0_encctrl.c   → fi_pwm_inv0_encctrl()
%   PE1/src/fi_pwm_inv0_idqctrl.c   → fi_pwm_inv0_idqctrl()
%   PE1/src/fi_pwm_inv0_svctrl.c    → fi_pwm_inv0_svctrl()
%   PE1/src/fi_1ms_inv0_idqcom.c    → fi_1ms_inv0_idqcom()
%
%   ※ plant_model_im() はシミュレーション専用の簡略化プラントモデルであり、
%     組み込み側に直接対応する関数はありません。
%
% 組み込み実機コードとの差分（主な仮定）：
%   ・実エンコーダは使わず、プラント力学から得られる速度を使用
%   ・DCバス電圧は一定（理想電源）として扱う
%   ・ADC電流計測ノイズは未モデル化
%   ・デッドタイム補償は未実装
%   ・idqctrl内の座標変換は簡略化し、プラントのdq電流を直接利用
%     （Clarke/Park変換を省略）
%   詳細は README_simulation.md を参照してください。

clear; clc; close all;

%% =====================================================================
%  1. パラメータ読み込み
% ======================================================================
% 制御周期、モータ定数、各種ゲイン、制限値などを構造体 p に読み込みます。
p = params_inv0();

%% =====================================================================
%  2. シナリオ設定（ここを編集すると挙動を変えられます）
% ======================================================================
T_SIM      = 2.0;        % [s] シミュレーション総時間

% [Nm] 外部トルク指令プロファイル（時間 t に応じて段階的に変更）、モータに与える目標トルク指令
%{
TQ_PROFILE = @(t) ...
    (t <  0.2) * 0.0 + ...
    (t >= 0.2 & t < 1.0) * 30.0 + ...
    (t >= 1.0 & t < 1.5) * 50.0 + ...
    (t >= 1.5) * 20.0;
%}
TQ_PROFILE = @(t) 20.0;

% [Nm] 負荷トルクプロファイル（本例では一定）、モータにかかる負荷トルク
LOAD_PROFILE = @(t) 5.0;

% [V] DCバス電圧（理想一定）
VDC = 48.0;

% 初期温度・基準温度 [°C]
% 組み込み側定義との対応をとるため、25°C開始としています。
T_MOT_INIT = 25.0;
T_R1_REF   = p.TMP_INV0_R1;
T_R2_REF   = p.TMP_INV0_R2;

% 制御モード
% 0: irms/angleモード、1: torque-mapモード
% 本シミュレーション（簡略化プラント）では 1 を使用。
CTRL_MODE  = 1;

%% =====================================================================
%  3. 時間設定
% ======================================================================
Ts_pwm  = p.TS_INV0_CTRL;       % [s] 100 µs PWM割り込み周期
Ts_1ms  = p.TS_INV0_CTRL * 10;  % [s] 1 ms タスク周期
N_SIM   = round(T_SIM / Ts_pwm);% [count] PWMステップ総数
N_1MS   = round(Ts_1ms / Ts_pwm); % [count] 1msあたりPWM回数（通常10）

%% =====================================================================
%  4. 状態変数初期化
%     （fim_gwork_inv0.h のグローバルワーク変数に相当）
% ======================================================================
s = struct();

% ---------------------------------------------------------------------
% プラント状態（簡略化モデル）
% ---------------------------------------------------------------------
s.id_meas        = 0.0;   % [A] d軸電流（計測値）
s.iq_meas        = 0.0;   % [A] q軸電流（計測値）

% fi_1ms_inv0_idqcom 互換の別名
% 組み込み由来関数内では *_ad 名称を参照するため、同じ値を保持します。
s.id_ad          = s.id_meas;
s.iq_ad          = s.iq_meas;

s.omega_mech     = 0.0;   % [rad/s] 機械角速度（ロータ）
s.theta_mech     = 0.0;   % [rad]   機械角
s.speed_mech_rpm = 0.0;   % [rpm]   機械回転数
s.tq_plant       = 0.0;   % [Nm]    プラントが発生した電磁トルク
s.tq_load        = 0.0;   % [Nm]    負荷トルク（毎ステップで上書き）
s.J              = 0.05;  % [kg·m^2] 慣性モーメント（簡略値）

% ---------------------------------------------------------------------
% モータモデルパラメータ（必要に応じて制御側が更新）
% ---------------------------------------------------------------------
s.r1_cmp         = p.R1_INV0;  % 一次抵抗補償値
s.r2_cmp         = p.R2_INV0;  % 二次抵抗補償値
s.lm             = p.LM_INV0;  % 励磁インダクタンス

% ---------------------------------------------------------------------
% DCバス関連（理想一定）
% ---------------------------------------------------------------------
s.vdc_ad         = VDC;        % [V] DCバス計測値（相当）

% ---------------------------------------------------------------------
% 温度状態（本シナリオでは一定温度）
% ---------------------------------------------------------------------
s.tmp_mot_max    = T_MOT_INIT; % [°C] モータ温度最大値（相当）

% ---------------------------------------------------------------------
% 1msタスク側：トルク・電流指令関連
% ---------------------------------------------------------------------
s.tq_ref_ext     = 0.0;                 % [Nm] 外部トルク要求
s.tq_ref         = 0.0;                 % [Nm] 内部トルク参照
s.tq_ref_tmp     = 0.0;                 % [Nm] レート制限後トルク参照
s.id_ctrl        = p.ID_INV0_REF_MIN;   % [A]  d軸電流制御値
s.iq_ctrl        = 0.0;                 % [A]  q軸電流制御値
s.tq_est         = 0.0;                 % [Nm] 推定トルク（LPF出力）
s.idc_est        = 0.0;                 % [A]  推定DC電流（LPF出力）
s.tq_ref_max     = 0.0;                 % [Nm] トルク上限制限
s.tq_ref_min     = 0.0;                 % [Nm] トルク下限制限
s.ctrl_mode      = CTRL_MODE;           % 制御モード

% ---------------------------------------------------------------------
% PWM割り込み側：角度・周波数・PLL関連
% ---------------------------------------------------------------------
s.wt_dq          = 0.0;   % [rad] 電気角（dq座標用積分角）
s.sin_wt         = 0.0;   % sin(wt_dq)
s.cos_wt         = 1.0;   % cos(wt_dq)
s.sin_wtsvctrl   = 0.0;   % SVPWM用 sin
s.cos_wtsvctrl   = 1.0;   % SVPWM用 cos
s.winv_ref       = 0.0;   % [rad/s] インバータ電気角周波数指令
s.wsl_ref        = 0.0;   % [rad/s] すべり角周波数指令
s.wr_pll         = 0.0;   % [rad/s] ロータ速度（PLL相当）
s.wr_pll_lpf     = 0.0;   % [rad/s] PLL速度LPF
s.wr_pll_intg    = 0.0;   % PLL積分状態
s.fd_ref         = p.LM_INV0 * p.ID_INV0_REF_MIN;  % [Wb] 磁束参照

% ---------------------------------------------------------------------
% PWM割り込み側：idq電流PI制御関連
% ---------------------------------------------------------------------
s.id_intg        = 0.0;   % d軸PI積分状態
s.iq_intg        = 0.0;   % q軸PI積分状態
s.id_ref         = p.ID_INV0_REF_MIN;  % d軸電流参照
s.iq_ref         = 0.0;                % q軸電流参照

s.vd_ref         = 0.0;   % [V] d軸電圧参照
s.vq_ref         = 0.0;   % [V] q軸電圧参照
s.vdq_ref        = 0.0;   % [V] 電圧ベクトル振幅（sqrt(vd^2 + vq^2)相当）

s.va_ref         = 0.0;   % [V] α軸電圧参照
s.vb_ref         = 0.0;   % [V] β軸電圧参照

s.pwr_lpf        = 0.0;   % 電力LPF状態
s.fw_intg        = 0.0;   % 弱め界磁制御 積分状態
s.fw_id_cmp      = 0.0;   % 弱め界磁 d軸補償量
s.m_lpf          = 0.0;   % 変調率LPF状態

% ---------------------------------------------------------------------
% SVPWM出力
% ---------------------------------------------------------------------
s.vu = 0.0; s.vv = 0.0; s.vw = 0.0; % [V] 相電圧指令
s.mu = 0.0; s.mv = 0.0; s.mw = 0.0; % [-] 変調率

% ---------------------------------------------------------------------
% 有効フラグ（組み込みの u1_flag_enable_* 相当）
% ---------------------------------------------------------------------
s.flag_r1_cmp    = p.ENABLE_INV0_R1_CMP;
s.flag_r2_cmp    = p.ENABLE_INV0_R2_CMP;

% ---------------------------------------------------------------------
% コントローラ関数互換のために必要な追加フィールド
% （命名差分吸収を目的とした互換用状態）
% ---------------------------------------------------------------------
s.pwm_status      = 1;         % 1: PWM動作中, 0: 停止
s.vdc_lpf         = VDC;       % [V] DCバスLPF値
s.power_p123_lpf  = 0.0;       % 電力LPF状態（別名）
s.vd_ctrli        = 0.0;       % d軸PI積分（別名）
s.vq_ctrli        = 0.0;       % q軸PI積分（別名）
s.tmp_igbt        = T_MOT_INIT;% [°C] IGBT温度
s.tmp_mot1        = T_MOT_INIT;% [°C] モータ温度1
s.tmp_mot2        = T_MOT_INIT;% [°C] モータ温度2
s.idq_vdqctrli    = 0.0;       % 弱め界磁積分（別名）
s.idq_ctrl        = p.ID_INV0_REF_MIN; % 電流ベクトル大きさ（FW用）

% PLL状態（fi_pwm_inv0_encctrl 内で使用）
s.wt_pll          = 0.0;       % [rad] PLL追従角
s.wr_enc_pll      = 0.0;       % [rad/s] PLL速度出力
s.wr_enc_pllp     = 0.0;       % PLL比例項
s.wr_enc_plli     = 0.0;       % PLL積分項
s.wr_pll_lpf_abs  = 0.0;       % |wr_pll_lpf|
s.winv_ref_abs    = 0.0;       % |winv_ref|
s.speed_lpf       = 0.0;       % [rpm] 速度LPF

%% =====================================================================
%  5. ログ配列の初期化
% ======================================================================
% 可視化や解析に使う時系列データを格納します。
LOG_T        = zeros(1, N_SIM);  % シミュレーション時刻 [s]
LOG_TQ_REF   = zeros(1, N_SIM);  % トルク指令値（制御へ与える目標トルク）[Nm]
LOG_TQ_EST   = zeros(1, N_SIM);  % トルク推定値（制御内部の推定トルク）[Nm]
LOG_TQ_PLANT = zeros(1, N_SIM);  % プラント側トルク（モデルが実際に発生したトルク）[Nm]

LOG_ID_REF   = zeros(1, N_SIM);  % d軸電流指令 id* [A]
LOG_IQ_REF   = zeros(1, N_SIM);  % q軸電流指令 iq* [A]
LOG_ID_MEAS  = zeros(1, N_SIM);  % d軸電流実測（またはプラント出力）id [A]
LOG_IQ_MEAS  = zeros(1, N_SIM);  % q軸電流実測（またはプラント出力）iq [A]

LOG_VD       = zeros(1, N_SIM);  % d軸電圧指令 vd [V]
LOG_VQ       = zeros(1, N_SIM);  % q軸電圧指令 vq [V]
LOG_VA       = zeros(1, N_SIM);  % 三相a相電圧指令 va（dq→abc変換後）[V]
LOG_VB       = zeros(1, N_SIM);  % 三相b相電圧指令 vb（dq→abc変換後）[V]
LOG_MU       = zeros(1, N_SIM);  % SVPWM変調率 u相（デューティ相当, 正規化値）
LOG_MV       = zeros(1, N_SIM);  % SVPWM変調率 v相（デューティ相当, 正規化値）
LOG_MW       = zeros(1, N_SIM);  % SVPWM変調率 w相（デューティ相当, 正規化値）

LOG_RPM      = zeros(1, N_SIM);  % ロータ回転速度 [rpm]
LOG_WSL      = zeros(1, N_SIM);  % すべり角周波数 ωsl [rad/s]
LOG_WINV     = zeros(1, N_SIM);  % インバータ電気角周波数 ωinv（同期角速度）[rad/s]
LOG_WTQ      = zeros(1, N_SIM);  % トルク制御系で使う角速度（トルク演算用の速度量）[rad/s]
LOG_LM       = zeros(1, N_SIM);  % 励磁インダクタンス Lm（マップ/推定で使用）[H or mH ※実装定義に依存]

%% =====================================================================
%  6. メインシミュレーションループ
% ======================================================================
fprintf('Starting simulation: %.1f s, Ts_pwm=%.0f µs ...\n', T_SIM, Ts_pwm*1e6);
t_now = 0.0;

for k = 1:N_SIM
    % 現在時刻 [s]
    t_now = (k-1) * Ts_pwm;

    % -----------------------------------------------------------------
    % 外部入力の更新（毎PWMステップ）
    % -----------------------------------------------------------------
    s.tq_ref_ext = TQ_PROFILE(t_now);   % 外部トルク指令
    s.tq_load    = LOAD_PROFILE(t_now); % 負荷トルク

    % -----------------------------------------------------------------
    % 6a) 1msタスク（N_1MS回に1回実行）
    %     対応: fi_1ms_inv0_idqcom.c / fi_1ms_inv0_idqcom()
    % -----------------------------------------------------------------
    if mod(k-1, N_1MS) == 0
        s = fi_1ms_inv0_idqcom(s, p);
    end

    % -----------------------------------------------------------------
    % 6b) PWM割り込み：エンコーダ/角度/すべり計算
    %     対応: fi_pwm_inv0_encctrl.c / fi_pwm_inv0_encctrl()
    %
    %     ※簡略化プラントのため、ロータ速度は実エンコーダではなく
    %       力学モデルの omega_mech から与えます。
    % -----------------------------------------------------------------
    s.wr_pll = s.omega_mech * p.PF_INV0; % [rad/s] 電気角速度
    s = fi_pwm_inv0_encctrl(s, p);

    % -----------------------------------------------------------------
    % 6c) PWM割り込み：dq電流PI制御
    %     対応: fi_pwm_inv0_idqctrl.c / fi_pwm_inv0_idqctrl()
    % -----------------------------------------------------------------
    s = fi_pwm_inv0_idqctrl(s, p);

    % -----------------------------------------------------------------
    % 6d) PWM割り込み：SVPWM生成
    %     対応: fi_pwm_inv0_svctrl.c / fi_pwm_inv0_svctrl()
    % -----------------------------------------------------------------
    s = fi_pwm_inv0_svctrl(s, p);

    % -----------------------------------------------------------------
    % 6e) プラント更新：誘導電動機の力学・電気モデル
    %     （シミュレーション専用、組み込み対応なし）
    % -----------------------------------------------------------------
    s = plant_model_im(s, p, Ts_pwm);

    % 1ms側関数が参照する *_ad 名称へ同期
    % （id_meas/iq_meas と id_ad/iq_ad の整合を毎ステップ維持）
    s.id_ad = s.id_meas;
    s.iq_ad = s.iq_meas;

    % -----------------------------------------------------------------
    % 6f) ログ保存
    % -----------------------------------------------------------------
    LOG_T(k)        = t_now;             % 現在時刻 [s]
    LOG_TQ_REF(k)   = s.tq_ref_tmp;      % 制御に実際に入力するトルク指令（整形後）[Nm]
    LOG_TQ_EST(k)   = s.tq_est;          % 制御内部のトルク推定値 [Nm]
    LOG_TQ_PLANT(k) = s.tq_plant;        % プラント（モータモデル）の実トルク [Nm]
    
    LOG_ID_REF(k)   = s.id_ref;          % d軸電流指令値 id* [A]
    LOG_IQ_REF(k)   = s.iq_ref;          % q軸電流指令値 iq* [A]
    LOG_ID_MEAS(k)  = s.id_meas;         % d軸電流の実測（モデル出力）id [A]
    LOG_IQ_MEAS(k)  = s.iq_meas;         % q軸電流の実測（モデル出力）iq [A]
    
    LOG_VD(k)       = s.vd_ref;          % d軸電圧指令値 vd* [V]
    LOG_VQ(k)       = s.vq_ref;          % q軸電圧指令値 vq* [V]
    LOG_VA(k)       = s.va_ref;          % a相電圧指令値 va*（dq→abc変換後）[V]
    LOG_VB(k)       = s.vb_ref;          % b相電圧指令値 vb*（dq→abc変換後）[V]
    
    LOG_MU(k)       = s.mu;              % PWM変調率 u相（デューティ相当の正規化値）[-]
    LOG_MV(k)       = s.mv;              % PWM変調率 v相（デューティ相当の正規化値）[-]
    LOG_MW(k)       = s.mw;              % PWM変調率 w相（デューティ相当の正規化値）[-]
    
    LOG_RPM(k)      = s.speed_mech_rpm;  % 機械回転速度 [rpm]
    LOG_WSL(k)      = s.wsl_ref;         % すべり角周波数指令 ωsl [rad/s]
    LOG_WINV(k)     = s.winv_ref;        % インバータ電気角周波数 ωinv [rad/s]
    LOG_WTQ(k)      = s.wt_dq;           % dq座標系で用いる電気角速度（トルク演算系）[rad/s]
    LOG_LM(k)       = s.lm;              % 励磁インダクタンス Lm [H]（実装定義によっては[mH]）
end

fprintf('Simulation complete.\n');

%% =====================================================================
%  7. 結果プロット
% ======================================================================

% ---------------------------------------------------------------------
% 図1: トルクと回転速度
% ---------------------------------------------------------------------
figure('Name','IMベクトル制御 — トルクと回転速度','NumberTitle','off');

subplot(3,1,1);
plot(LOG_T, LOG_TQ_REF,'b--', LOG_T, LOG_TQ_EST,'r-', LOG_T, LOG_TQ_PLANT,'k-');
ylabel('トルク [Nm]');
legend('トルク指令','トルク推定','プラントトルク');
grid on;
title('トルク応答');

subplot(3,1,2);
plot(LOG_T, LOG_RPM,'k-');
ylabel('回転速度 [rpm]');
xlabel('時間 [s]');
grid on;
title('ロータ回転速度');

subplot(3,1,3);
plot(LOG_T, LOG_WSL,'b-', LOG_T, LOG_WINV,'r-');
ylabel('角周波数 [rad/s]');
xlabel('時間 [s]');
legend('すべり角周波数 \omega_{sl}','インバータ角周波数 \omega_{inv}');
grid on;
title('すべり周波数 / インバータ周波数');

figure('Name','IMベクトル制御 — dq電流','NumberTitle','off');

subplot(2,1,1);
plot(LOG_T, LOG_ID_REF,'b--', LOG_T, LOG_ID_MEAS,'b-');
ylabel('id [A]');
legend('id指令','id実測');
grid on;
title('d軸電流');

subplot(2,1,2);
plot(LOG_T, LOG_IQ_REF,'r--', LOG_T, LOG_IQ_MEAS,'r-');
ylabel('iq [A]');
xlabel('時間 [s]');
legend('iq指令','iq実測');
grid on;
title('q軸電流');

figure('Name','IMベクトル制御 — dq電圧と変調率','NumberTitle','off');

subplot(2,1,1);
plot(LOG_T, LOG_VD,'b-', LOG_T, LOG_VQ,'r-');
ylabel('電圧 [V]');
legend('vd','vq');
grid on;
title('dq軸電圧指令');

subplot(2,1,2);
plot(LOG_T, LOG_MU,'b-', LOG_T, LOG_MV,'g-', LOG_T, LOG_MW,'r-');
ylabel('変調率 [-]');
xlabel('時間 [s]');
legend('mu','mv','mw');
grid on;
title('SVPWM変調率');

figure('Name','IMベクトル制御 — 励磁インダクタンス','NumberTitle','off');
plot(LOG_T, LOG_LM * 1e3);
ylabel('Lm [mH]');
xlabel('時間 [s]');
grid on;
title('励磁インダクタンス Lm（マップ出力）');
%}